// ===========================================================================
// a. DIRTY-TREE GUARD
// ===========================================================================
// `vercel --prod` ships the WORKING TREE, not a commit — so any tracked,
// modified/staged file (possibly another concurrent session's uncommitted
// work) would ship live. BLOCK on tracked changes; WARN on untracked (often
// scratch). This is the single biggest known foot-gun in this repo.
/**
 * Paths the CLI itself writes and then tells the user to commit. Flagging them
 * as "likely scratch" right after `brief`/`handoff`/`init` is dishonest
 * (finding: self-artifacts-trip-dirty-guard). Matched as exact files or under
 * the marker dirs.
 */
function isOwnArtifact(rel) {
  const p = String(rel || "").replace(/\\/g, "/").replace(/^\.\//, "");
  if (
    p === "PROJECT-BRIEF.md" ||
    p === "HANDOFF.md" ||
    p === "AGENTS.md" ||
    p === ".cursorrules" ||
    p === ".windsurfrules" ||
    p === ".clinerules" ||
    p === "CLAUDE.md" ||
    p === ".github/copilot-instructions.md" ||
    p === ".github/workflows/getadvantage.yml"
  ) {
    return true;
  }
  if (p.startsWith(".getadvantage/") || p.startsWith(".ship-safe/")) return true;
  return false;
}

/**
 * The subset of own artifacts the CLI REWRITES on every run (brief/handoff and
 * the marker dirs). A tracked, in-place modification of these is expected churn,
 * so it stays informational. The OTHER own artifacts (CLAUDE.md, AGENTS.md, the
 * editor rules files, the CI workflow) are seeded ONCE and then hand-maintained —
 * a tracked edit or deletion there is real human/agent work (or tampering), not
 * CLI churn, so it must go through the normal tracked-change gate instead of being
 * reported as "clean of ship-risk" (finding: dirty-own-artifact-tracked-mod-pass).
 *
 * Policy config (`config.json` under the marker dirs) is never rewritten by the
 * CLI — it authorizes secret ignores. Tracked/staged edits there are ship-risk,
 * not regenerated churn (0.8.3 Fable audit P1).
 * Intent Contract (`intent.json`) is likewise human-authored trust material —
 * never regenerated by the CLI; tracked edits are ship-risk (0.10.0).
 */
function isRegeneratedArtifact(rel) {
  const p = String(rel || "").replace(/\\/g, "/").replace(/^\.\//, "");
  if (p === "PROJECT-BRIEF.md" || p === "HANDOFF.md") return true;
  if (p === ".getadvantage/config.json" || p === ".ship-safe/config.json") return false;
  if (p === ".getadvantage/intent.json" || p === ".ship-safe/intent.json") return false;
  if (p.startsWith(".getadvantage/") || p.startsWith(".ship-safe/")) return true;
  return false;
}

export function checkDirtyTree(cwd) {
  // gitRaw (NOT git) — porcelain's leading status columns are space-significant,
  // so we must not trim the output before parsing.
  const porcelain = gitRaw(["status", "--porcelain"], { cwd });
  if (!porcelain.trim()) {
    return result("pass", "Dirty-tree guard", "Working tree is clean — nothing unintended would ship.");
  }

  const lines = porcelain.split("\n").filter((l) => l.length > 0);
  const tracked = []; // modified / staged / renamed / deleted tracked files
  const untracked = []; // ?? — new files git isn't tracking yet
  const own = []; // getAdvantage brain/marker artifacts (informational)

  for (const line of lines) {
    // Porcelain v1: XY<space>path  (X=staged, Y=worktree). "??" = untracked.
    // Renames: "R  old -> new" — take the right-hand path for classification.
    const xy = line.slice(0, 2);
    let file = line.slice(3);
    if (file.includes(" -> ")) file = file.split(" -> ").pop();
    if (isOwnArtifact(file)) {
      const untrackedNew = xy === "??";
      const deleted = xy.includes("D");
      // Informational ONLY when it is a just-generated untracked file, or an
      // expected in-place rewrite of a file the CLI regenerates every run. A
      // tracked edit to a seed file (CLAUDE.md/AGENTS.md/rules/workflow), or ANY
      // deletion, is real work → fall through to the normal tracked gate so we
      // never claim "clean of ship-risk" over changes the CLI did not make.
      if (untrackedNew || (isRegeneratedArtifact(file) && !deleted)) {
        own.push(file);
        continue;
      }
    }
    if (xy === "??") untracked.push(file);
    else tracked.push(`${xy.trim() || xy} ${file}`);
  }

  if (tracked.length > 0) {
    return result(
      "fail",
      "Dirty-tree guard",
      `${tracked.length} tracked file${pl(tracked.length)} modified/staged — a 'vercel --prod' would ship this unintended work.`,
      [
        ...tracked.slice(0, 20).map((t) => t),
        ...(tracked.length > 20 ? [`…and ${tracked.length - 20} more`] : []),
        "Commit, stash, or revert before shipping. Deploy from a clean detached worktree of the intended commit.",
        ...(own.length
          ? [`(Also ${own.length} getAdvantage brain/marker file${pl(own.length)} dirty — commit those when ready; they don't block alone.)`]
          : []),
      ],
    );
  }

  // Only own artifacts dirty → pass with a note (the tool told you to create them).
  if (untracked.length === 0 && own.length > 0) {
    return result(
      "pass",
      "Dirty-tree guard",
      `Working tree clean of ship-risk; ${own.length} getAdvantage brain/marker file${pl(own.length)} uncommitted (expected after brief/handoff — commit when ready).`,
      own.slice(0, 20),
    );
  }

  // Only untracked files → warn, list them (may be intentional new work).
  const extras = [
    ...untracked.slice(0, 20),
    ...(untracked.length > 20 ? [`…and ${untracked.length - 20} more`] : []),
  ];
  if (own.length) {
    extras.push(
      `(Plus ${own.length} getAdvantage brain/marker file${pl(own.length)} — not listed as risk; commit when ready.)`,
    );
  }
  return result(
    "warn",
    "Dirty-tree guard",
    `${untracked.length} untracked file${pl(untracked.length)} present (not yet tracked — confirm they are meant to ship, or add them to .gitignore).`,
    extras,
  );
}

// ===========================================================================
// b. SECRET SCAN
// ===========================================================================
// What we scan for: OpenAI, Anthropic, Stripe (live/restricted/webhook), AWS,
// GitHub (classic + fine-grained), Google OAuth, Slack, SendGrid, npm access
// tokens, bare JWTs (header-validated), database URLs with embedded passwords,
// getAdvantage's own platform keys (adv_live_), Vercel tokens, KV/Redis REST
// credentials, "Bearer <token>" literals, and private-key blocks.
// A match BLOCKS (✗); we print the file + a masked FINGERPRINT, never the
// full secret. Binary/lockfiles/node_modules/.git are skipped.

// All patterns carry the /g flag: we matchAll and report the hit COUNT per
// file, not just the first occurrence.
// Shared validator: real API keys contain at least one digit; CSS class-name
// chains ("sk-circle-fade-dot-before-anim") and prose practically never do.
const hasDigit = (tok) => /[0-9]/.test(tok);

const SECRET_PATTERNS = [
  // --- from app/lib/safety.ts ---
  // Anthropic BEFORE OpenAI: `sk-ant-…` also matches the broader sk- shape, so
  // the specific pattern must claim it first (and openai's validator skips it).
  { id: "anthropic", label: "Anthropic secret key", re: /\bsk-ant-[A-Za-z0-9_-]{20,}/g, validate: hasDigit },
  {
    id: "openai",
    label: "OpenAI secret key",
    re: /\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}/g,
    // Digit required (kills CSS-class false positives); sk-ant- is Anthropic's.
    validate: (tok) => hasDigit(tok) && !tok.startsWith("sk-ant-"),
  },
  { id: "stripe-live", label: "Stripe live secret key", re: /\bsk_live_[A-Za-z0-9]{20,}/g },
  { id: "stripe-restricted", label: "Stripe restricted key", re: /\brk_live_[A-Za-z0-9]{20,}/g },
  { id: "aws", label: "AWS access key id", re: /\bAKIA[0-9A-Z]{16}\b/g },
  { id: "github-pat", label: "GitHub personal access token", re: /\bghp_[A-Za-z0-9]{36}\b/g },
  { id: "github-fine", label: "GitHub fine-grained token", re: /\bgithub_pat_[A-Za-z0-9_]{22,}\b/g },
  { id: "google-oauth", label: "Google OAuth secret", re: /\bGOCSPX-[A-Za-z0-9_-]{20,}\b/g },
  { id: "slack", label: "Slack token", re: /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/g },
  // Full PEM block (BEGIN…END), not the header alone. Header-only matches make
  // every key of the same type share one secretAuthId — a hash copied from one
  // fixture must never authorize a different private key (0.8.3 re-review P1).
  {
    id: "private-key",
    label: "Private key block",
    re: /-----BEGIN ((?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY)-----[\s\S]*?-----END \1-----/g,
  },
  // Incomplete / truncated PEM: BEGIN present without a matching END for that
  // key type. Full-block regex misses material when the footer is stripped —
  // removing the footer must not turn NO-GO into GO (0.8.3 final re-review P1).
  // Match string is the constant header → non-unique; value/hash allowlisting
  // is refused in secretAllowDecision for this patternId.
  {
    id: "private-key-incomplete",
    label: "Incomplete private key block",
    re: /-----BEGIN ((?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY)-----/g,
    validate: (_tok, m) => {
      const keyType = m?.[1];
      if (!keyType || m.index == null) return false;
      // Escape type for RegExp (spaces/letters only in practice, but stay strict).
      const esc = String(keyType).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const fromHere = m.input.slice(m.index);
      const complete = new RegExp(
        `^-----BEGIN ${esc}-----[\\s\\S]*?-----END ${esc}-----`,
      );
      // Fire only when this BEGIN is not the start of a complete PEM block.
      return !complete.test(fromHere);
    },
  },
  { id: "sendgrid", label: "SendGrid key", re: /\bSG\.[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}\b/g },
  // --- from CLAUDE.md hard-rule #2 (the pre-commit scan literals) ---
  { id: "stripe-webhook", label: "Stripe webhook secret (whsec_)", re: /\bwhsec_[A-Za-z0-9]{20,}/g },
  { id: "vercel-token", label: "Vercel token (vcp_)", re: /\bvcp_[A-Za-z0-9]{20,}/g },
  { id: "kv-rest", label: "KV/Redis REST credential", re: /\bKV_REST_API_(?:URL|TOKEN|READ_ONLY_TOKEN)\s*=\s*\S+/g },
  // getAdvantage's OWN platform key format: adv_live_ + lowercase base36. A
  // dedicated pattern because the generic Bearer heuristic below requires MIXED
  // case + a digit and would miss an all-lowercase token like this one.
  { id: "getadvantage-key", label: "getAdvantage platform key (adv_live_)", re: /\badv_live_[a-z0-9]{16,}\b/g },
  // --- coverage additions (v0.6.0) ---
  // npm access/automation token (the `.npmrc _authToken=npm_…` leak).
  { id: "npm-token", label: "npm access token", re: /\bnpm_[A-Za-z0-9]{36}\b/g },
  // Bare JWT (three base64url segments, no "Bearer" prefix needed). To keep
  // false positives near zero we only flag it if the FIRST segment decodes to
  // a JSON object with an `alg` or `typ` field — i.e. a real JWT header.
  {
    id: "jwt",
    label: "JSON Web Token (JWT)",
    re: /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b/g,
    validate: (tok) => {
      try {
        const header = JSON.parse(Buffer.from(tok.split(".")[0], "base64url").toString("utf8"));
        return typeof header === "object" && header !== null && ("alg" in header || "typ" in header);
      } catch {
        return false;
      }
    },
  },
  // Database URL with an embedded password (postgres://user:PASS@host).
  // The validator runs on the captured password + host and skips (a) obvious
  // placeholder / interpolated passwords ("mypassword", "changeme3", …) and
  // (b) ANY URL whose host is a local dev target (localhost, 127.0.0.1,
  // 0.0.0.0, ::1, host.docker.internal) — a dev URL is not a production leak.
  // So docs + examples never trip a NO-GO, while a real credential still does.
  {
    id: "db-url-password",
    label: "Database URL with embedded password",
    re: /\bpostgres(?:ql)?:\/\/[^\s:/@'"]+:([^@\s'"]{8,})@([^\s'"/]+)/g,
    validate: (pw, m) => {
      if (/[<>{}$%]/.test(pw)) return false;
      if (/^(?:pass(?:word)?|passwd|secret|example|changeme|test|postgres|admin|root|1234(?:5678?9?)?|x{4,}|\*{4,})$/i.test(pw)) return false;
      // Placeholder passwords: my/your/… + pass(word)/passwd/pwd/secret/changeme (+digits).
      if (/^(?:my|your|db|dummy|sample|local|test|example|demo)?(?:pass(?:word)?|passwd|pwd|secret|changeme)\d*$/i.test(pw)) return false;
      // Local/dev hosts are never a production leak.
      const host = String(m?.[2] ?? "").replace(/:\d+$/, "").toLowerCase();
      if (["localhost", "127.0.0.1", "0.0.0.0", "::1", "host.docker.internal"].includes(host)) return false;
      return true;
    },
  },
  // "Bearer <token>" literal. The CLAUDE.md pre-commit scan lists "Bearer " as a
  // tell. We capture the token and only flag it if it LOOKS like a real
  // credential (mixed case + a digit, ≥20 chars) — so legitimate test fixtures
  // and placeholders like `Bearer test_cron_secret...` or `Bearer ${token}`
  // don't trip a false NO-GO. The `validate` predicate runs on the captured group.
  {
    id: "bearer",
    label: "Bearer auth token literal",
    re: /\bBearer\s+([A-Za-z0-9_\-.]{20,})/g,
    validate: (tok) => /[a-z]/.test(tok) && /[A-Z]/.test(tok) && /[0-9]/.test(tok),
  },
];

// Files we never scan (binary-ish, generated, vendored).
//
// ⚠ Deliberately NOT skipped: .env* files AND build-output dirs (dist/build/
// coverage) AND committed Next.js browser assets under .next/static/**.
// filesToScan() runs through git ls-files, which honours .gitignore — so a
// normally-generated dir only ever reaches the scan when the user COMMITTED it.
// A dir/basename skip here could therefore only suppress the DANGEROUS case:
// a bundled/copied key inside committed build output (the classic vibe-coder
// `git add .` of a dist folder). Skipping .env was a real hole in ≤0.5.0 (fixed
// 0.6.0); skipping build dirs was the same silent-GO hole
// (finding: F1-buildpath-secret-skip); blanket-skipping every `.next` path
// segment was the same class of hole for Next.js client bundles
// (finding: F-client-bundle-next-static). Truly-huge trees that are normally
// gitignored stay skipped for perf — if they're committed, that's a separate smell.
//
// Honesty boundary for `.next`:
//   • SCAN  committed text under `.next/static/**` (JS/CSS/chunks/maps that
//     browsers actually load — the place a private key can ship to the client).
//   • SKIP  other `.next` segments (cache, server, types, traces, BUILD_ID, …)
//     which are not browser static assets and are often binary/huge.
//   • Binary/ext skips (SKIP_EXT, looksBinary) still apply under static/.
// This is pattern coverage of committed client build output — not a guarantee
// that every secret shape is known, and public name prefixes (NEXT_PUBLIC_*,
// VITE_*) are NOT an exemption: only the value's shape decides a hit.
const SKIP_DIR = new Set([".git", "node_modules", ".vercel", ".data"]);
// Lockfiles USED to be skipped for perf, but a committed npm/yarn _authToken (or a
// key pasted into one) then slipped through silently — so nothing is skipped by
// basename anymore; they're scanned like any other text file.
const SKIP_BASENAME = new Set([]);
// Truly BINARY assets only (images, fonts, video, archives, PDFs). Text formats
// that can carry a copied key are deliberately NOT skipped so the README's "every
// tracked text file" claim is honest: .map sourcemaps embed original sourcesContent
// (a classic place a bundled key hides), .svg is XML, lockfiles are JSON/YAML.
const SKIP_EXT = new Set([
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf",
  ".woff", ".woff2", ".ttf", ".eot", ".mp4", ".webm", ".zip", ".gz",
]);

/**
 * True when a relative path should be excluded from the secret scan.
 * Always skip .git / node_modules / .vercel / .data. For `.next`, skip unless
 * the path is under a `.next/static/` segment (committed browser assets).
 */
function shouldSkipSecretPath(rel) {
  const segs = rel.split(/[\\/]/).filter(Boolean);
  for (let i = 0; i < segs.length; i++) {
    const seg = segs[i];
    if (SKIP_DIR.has(seg)) return true;
    if (seg === ".next") {
      // Only client static assets under .next/static/** are scanned.
      if (segs[i + 1] !== "static") return true;
    }
  }
  return false;
}

const MAX_FILE_BYTES = 2_000_000; // full-scan cap (same cap as safety.ts corpus)
const PARTIAL_CHUNK_BYTES = 262_144; // oversized files: scan first + last 256 KB

/** Heuristic: does this buffer look binary? (null byte in the first 4KB) */
function looksBinary(buf) {
  const n = Math.min(buf.length, 4096);
  for (let i = 0; i < n; i++) if (buf[i] === 0) return true;
  return false;
}

/** UTF-16 encoding implied by a leading BOM, or null. FF FE = LE (the Windows
 *  PowerShell 5.1 default for `>` / Out-File), FE FF = BE. */
function bomEncoding(buf) {
  if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) return "utf16le";
  if (buf.length >= 2 && buf[0] === 0xfe && buf[1] === 0xff) return "utf16be";
  return null;
}

/** Decode UTF-16 bytes to a JS string. `hasBom` strips the leading 2-byte BOM;
 *  BE is byte-swapped to LE (Node has no utf16be decoder). */
function decodeUtf16(buf, be, hasBom) {
  const body = hasBom ? buf.subarray(2) : buf;
  if (!be) return body.toString("utf16le");
  const swapped = Buffer.allocUnsafe(body.length - (body.length % 2));
  for (let i = 0; i + 1 < body.length; i += 2) {
    swapped[i] = body[i + 1];
    swapped[i + 1] = body[i];
  }
  return swapped.toString("utf16le");
}

/** Decode a whole-file buffer to scannable text, honoring a UTF-16/UTF-8 BOM.
 *  Returns null for genuine binary (caller skips). Without the UTF-16 branch, a
 *  UTF-16-LE file has a NUL byte after every ASCII char, trips looksBinary, and
 *  is skipped silently — so a committed secret in a PowerShell-authored notes
 *  file passes the gate (a false GO). BOM detection is the reliable signal
 *  because both PowerShell and most Windows editors write the BOM. */
function decodeText(buf) {
  const enc = bomEncoding(buf);
  if (enc) return decodeUtf16(buf, enc === "utf16be", /* hasBom */ true);
  if (looksBinary(buf)) return null;
  return buf.toString("utf8");
}

/** Read the first and last PARTIAL_CHUNK_BYTES of an oversized file without
 *  loading the whole thing. Returns { head, tail } buffers (tail may be null
 *  if reading it fails). Read-only. */
function readHeadTail(abs, size) {
  const fd = openSync(abs, "r");
  try {
    const head = Buffer.alloc(PARTIAL_CHUNK_BYTES);
    const hn = readSync(fd, head, 0, PARTIAL_CHUNK_BYTES, 0);
    const tail = Buffer.alloc(PARTIAL_CHUNK_BYTES);
    const tn = readSync(fd, tail, 0, PARTIAL_CHUNK_BYTES, Math.max(0, size - PARTIAL_CHUNK_BYTES));
    return { head: head.subarray(0, hn), tail: tail.subarray(0, tn) };
  } finally {
    closeSync(fd);
  }
}

/** Files to scan: tracked + staged + (added) untracked-but-not-ignored, deduped.
 *  We deliberately DON'T scan gitignored files (the local .env lives there and
 *  is supposed to hold secrets). */
function filesToScan(cwd) {
  const set = new Set();
  // gitFilesZ (NUL-terminated) — NOT the newline-split gitSafe: git quotes +
  // octal-escapes non-ASCII paths by default, which then fail to open and drop
  // out of the scan silently (a false GO on any repo with an umlaut filename).
  // Tracked files.
  for (const f of gitFilesZ(["ls-files"], { cwd })) set.add(f);
  // Untracked-but-not-ignored (new files a dev created; --others honours .gitignore).
  for (const f of gitFilesZ(["ls-files", "--others", "--exclude-standard"], { cwd })) set.add(f);
  return [...set];
}

export function checkSecrets(cwd) {
  const files = filesToScan(cwd);
  // (file,label) → { fp, count } so repeated hits are COUNTED, not dropped.
  const hits = new Map();
  // Allowlisted hits (built-in EXAMPLE keys + `.getadvantage/config.json` rules).
  // Always disclosed — never a silent false GO (finding: gate-placeholder-false-positive).
  const allowed = new Map(); // (file,label,reason) → { fp, count, reason }
  let scanned = 0;
  let partial = 0; // oversized files scanned head+tail only
  const partialFiles = []; // relative paths of those files (named in the note)
  const policy = loadPolicy(cwd);

  for (const rel of files) {
    const base = path.basename(rel);
    const ext = path.extname(rel).toLowerCase();
    if (SKIP_BASENAME.has(base)) continue;
    if (SKIP_EXT.has(ext)) continue;
    // Skip vendored/cache dirs; keep committed client build assets (dist/,
    // build/, .next/static/**) so a bundled key cannot silent-GO.
    if (shouldSkipSecretPath(rel)) continue;

    const abs = path.join(cwd, rel);
    let text;
    let isPartial = false;
    try {
      const st = statSync(abs);
      if (!st.isFile()) continue;
      if (st.size > MAX_FILE_BYTES) {
        // Oversized: NEVER skip silently. Scan the first + last 256 KB and
        // say so in the summary — a secret appended to a giant file is a
        // classic miss.
        const { head, tail } = readHeadTail(abs, st.size);
        const enc = bomEncoding(head);
        if (enc) {
          // UTF-16: decode both chunks (head carries the BOM, tail doesn't).
          const be = enc === "utf16be";
          text = `${decodeUtf16(head, be, true)}\n${decodeUtf16(tail, be, false)}`;
        } else {
          if (looksBinary(head)) continue;
          text = `${head.toString("utf8")}\n${tail.toString("utf8")}`;
        }
        isPartial = true;
      } else {
        const decoded = decodeText(readFileSync(abs));
        if (decoded === null) continue;
        text = decoded;
      }
    } catch {
      continue; // unreadable / deleted-but-staged etc.
    }
    scanned++;
    if (isPartial) {
      partial++;
      partialFiles.push(rel);
    }

    for (const p of SECRET_PATTERNS) {
      for (const m of text.matchAll(p.re)) {
        // If the pattern has a capture group + validator (e.g. Bearer, JWT,
        // DB URL), apply the validator to the captured token so test
        // fixtures/placeholders don't trip. The full match array is passed
        // too, for validators that need more context (e.g. the DB-URL host).
        const token = m[1] ?? m[0];
        if (p.validate && !p.validate(token, m)) continue;
        const raw = m[0];
        const decision = secretAllowDecision(raw, {
          file: rel,
          patternId: p.id,
          policy,
        });
        if (decision.allowed) {
          const ak = `${rel}::${p.label}::${decision.reason}`;
          const prevA = allowed.get(ak);
          if (prevA) prevA.count++;
          else {
            allowed.set(ak, {
              file: rel,
              label: p.label,
              fp: decision.fp,
              authId: decision.authId,
              count: 1,
              reason: decision.reason,
            });
          }
          continue;
        }
        const k = `${rel}::${p.label}`;
        const prev = hits.get(k);
        if (prev) prev.count++;
        else {
          // Region from match index when defensible (1-based line/column).
          // Partial head+tail scans can mis-number middle lines — still emit
          // file + fingerprint; only attach region for full-file scans.
          let startLine;
          let startColumn;
          let endColumn;
          if (!isPartial && typeof m.index === "number" && m.index >= 0) {
            const rc = offsetToLineCol(text, m.index);
            startLine = rc.line;
            startColumn = rc.col;
            const end = offsetToLineCol(text, m.index + raw.length);
            if (end.line === rc.line) endColumn = end.col;
          }
          hits.set(k, {
            file: rel,
            label: p.label,
            patternId: p.id,
            fp: decision.fp,
            authId: decision.authId,
            count: 1,
            startLine,
            startColumn,
            endColumn,
          });
        }
      }
    }
  }

  const partialNames =
    partialFiles.slice(0, 5).join(", ") + (partial > 5 ? `, …and ${partial - 5} more` : "");
  const partialNote =
    partial > 0
      ? [`${partial} oversized file${pl(partial)} >2 MB scanned partially (first + last 256 KB each; scanned partially: ${partialNames}) — move giant blobs out of git for a full scan.`]
      : [];

  // Display fingerprint is human-readable only; sha256 auth id is the
  // copy-paste allowlist identity (never the full secret).
  const hitLine = (h) =>
    `${h.file} → ${h.label}: ${h.fp}${h.count > 1 ? ` (+${h.count - 1} more)` : ""}${h.authId ? ` · auth ${h.authId}` : ""}`;

  const allowedList = [...allowed.values()];
  const allowedNote =
    allowedList.length > 0
      ? [
          `${allowedList.length} allowlisted hit${pl(allowedList.length)} (disclosed, not blocking):`,
          ...allowedList.slice(0, 20).map(
            (h) =>
              `  ${hitLine(h)} [${h.reason}]`,
          ),
          ...(allowedList.length > 20 ? [`  …and ${allowedList.length - 20} more allowlisted`] : []),
        ]
      : [];
  const policyNote = (policy.warnings || []).map((w) => `policy: ${w}`);

  if (hits.size === 0) {
    const allowSummary =
      allowedList.length > 0
        ? ` (${allowedList.length} allowlisted hit${pl(allowedList.length)} disclosed)`
        : "";
    return result(
      "pass",
      "Secret scan",
      `Scanned ${scanned} tracked/staged file${pl(scanned)} — no leaked-secret patterns matched.${allowSummary}`,
      [...allowedNote, ...policyNote, ...partialNote],
    );
  }

  const hitList = [...hits.values()];
  const lines = hitList.map(
    (h) =>
      `${h.file} → ${h.label}: ${h.fp}${h.count > 1 ? ` (+${h.count - 1} more in this file)` : ""}${h.authId ? ` · auth ${h.authId}` : ""}`,
  );
  // Structured findings for SARIF (and optional --json consumers). Never carry
  // the raw match — only fingerprint, auth id, path, patternId, region.
  const findings = hitList.map((h) => {
    const remediation = secretHitRemediation(h);
    return {
      ruleId: `secret/${h.patternId || "unknown"}`,
      patternId: h.patternId,
      label: h.label,
      file: h.file,
      fp: h.fp,
      authId: h.authId,
      count: h.count,
      ...(typeof h.startLine === "number" ? { startLine: h.startLine } : {}),
      ...(typeof h.startColumn === "number" ? { startColumn: h.startColumn } : {}),
      ...(typeof h.endColumn === "number" ? { endColumn: h.endColumn } : {}),
      message: `${h.label}: ${h.fp}${h.authId ? ` · auth ${h.authId}` : ""}`,
      remediation,
    };
  });
  // Paste-ready remediation is additive only — never changes verdict/exit.
  const remediationNote = [];
  for (const h of hitList.slice(0, 30)) {
    remediationNote.push(...secretHitRemediation(h));
  }
  if (hitList.length > 30) {
    remediationNote.push(
      `…and ${hitList.length - 30} more blocking secret${pl(hitList.length - 30)} (same remedy shape: remove+rotate, or pattern-aware secrets.ignore).`,
    );
  }
  const r = result(
    "fail",
    "Secret scan",
    `${lines.length} possible secret${pl(lines.length)} in committed/staged files — remove + rotate before shipping.`,
    [...lines.slice(0, 30), ...remediationNote, ...allowedNote, ...policyNote, ...partialNote],
  );
  r.findings = findings;
  return r;
}

/**
 * Plain-language smallest-safe-next-edit for one blocking secret hit, including
 * a pattern-aware paste-ready `.getadvantage/config.json` `secrets.ignore`
 * snippet. Non-unique pattern ids (e.g. private-key-incomplete) never get a
 * hashes snippet — only paths/patternIds.
 *
 * @param {{ file: string, label: string, patternId?: string, authId?: string, fp?: string, startLine?: number }} h
 * @returns {string[]}
 */
function secretHitRemediation(h) {
  const filePosix = String(h.file || "").replace(/\\/g, "/");
  const loc =
    typeof h.startLine === "number"
      ? `${filePosix}:${h.startLine}`
      : filePosix;
  const patternId = h.patternId || "unknown";
  const nonUnique = isNonUniqueAuthPatternId(patternId);

  const lines = [
    `Smallest safe next edit — ${h.label} at ${loc}:`,
    `  Why it matters: this secret-shaped value is committed/staged and ships to every clone; git history keeps it until you rotate the credential at the provider.`,
    `  Preferred remedy: remove the value from the tree, rotate the credential, commit the removal, then re-run check.`,
    `  Escape hatch (deliberate, tracked, reviewable — suppressed hits stay printed as disclosed, never invisible): if this is an intentional fixture/sample, merge the paste-ready snippet below into tracked .getadvantage/config.json and commit it. Authorization reads the git index only.`,
  ];

  let ignore;
  if (nonUnique) {
    lines.push(
      `  Hash/value ignore is refused for pattern "${patternId}" because the match is not unique across keys (e.g. a constant PEM header collides). Use paths and/or patternIds only — never hashes for this pattern:`,
    );
    ignore = {
      paths: [filePosix],
      patternIds: [patternId],
    };
  } else if (h.authId) {
    lines.push(
      `  Paste-ready .getadvantage/config.json secrets.ignore (carries this finding's own auth id ${h.authId}):`,
    );
    ignore = {
      hashes: [h.authId],
    };
  } else {
    lines.push(
      `  Paste-ready .getadvantage/config.json secrets.ignore (path-scoped; no auth id available for this hit):`,
    );
    ignore = {
      paths: [filePosix],
    };
  }

  const doc = {
    version: 1,
    secrets: { ignore },
  };
  // JSON.stringify emits stable forward-slash paths (filePosix) — safe on Windows.
  const json = JSON.stringify(doc, null, 2);
  for (const jl of json.split("\n")) {
    lines.push(`  ${jl}`);
  }
  return lines;
}

/** 1-based line + column for a byte/char offset into a decoded UTF-16-or-UTF-8 string. */
function offsetToLineCol(text, offset) {
  let line = 1;
  let col = 1;
  const n = Math.min(offset, text.length);
  for (let i = 0; i < n; i++) {
    if (text[i] === "\n") {
      line++;
      col = 1;
    } else {
      col++;
    }
  }
  return { line, col };
}

// ===========================================================================
// b2. TRACKED .ENV FILE
// ===========================================================================
// A committed .env is a leak BY ITSELF, whatever it contains — git history
// keeps every value it ever held, and every clone gets a copy. This is the
// single most common vibe-coder leak (Lovable/Bolt/v0 templates read from
// .env, the first `git add .` commits it). BLOCK on any tracked .env*;
// WARN if a local .env exists but is not gitignored (one `git add .` away).
// Template files (.env.example / .sample / .template / .dist) are fine —
// their CONTENTS are still covered by the secret scan above.

const ENV_TEMPLATE_SUFFIX = /\.(?:example|sample|template|dist)$/i;

function isRealEnvFile(basename) {
  if (ENV_TEMPLATE_SUFFIX.test(basename)) return false;
  return basename === ".env" || basename.startsWith(".env.");
}

export function checkTrackedEnv(cwd) {
  const tracked = gitFilesZ(["ls-files"], { cwd })
    .filter((f) => isRealEnvFile(path.basename(f)));

  if (tracked.length > 0) {
    const r = result(
      "fail",
      "Tracked .env file",
      `${tracked.length} .env file${pl(tracked.length)} tracked by git — a committed .env is a leak by itself, whatever it contains.`,
      [
        ...tracked.slice(0, 10),
        "Remove it from git (git rm --cached <file>), add it to .gitignore, and ROTATE every key that file ever held — git history keeps old values.",
      ],
    );
    r.findings = tracked.map((file) => ({
      ruleId: "check/tracked-env-file",
      label: "Tracked .env file",
      file,
      message: "Committed .env is a leak by itself — remove from git, gitignore, rotate keys.",
    }));
    return r;
  }

  const untrackedEnv = gitFilesZ(["ls-files", "--others", "--exclude-standard"], { cwd })
    .filter((f) => isRealEnvFile(path.basename(f)));

  if (untrackedEnv.length > 0) {
    const r = result(
      "warn",
      "Tracked .env file",
      `${untrackedEnv.length} local .env file${pl(untrackedEnv.length)} are NOT gitignored — one 'git add .' away from committing your keys.`,
      [...untrackedEnv.slice(0, 10), "Add them to .gitignore so they can never be committed."],
    );
    r.findings = untrackedEnv.map((file) => ({
      ruleId: "check/tracked-env-file",
      label: "Unignored .env file",
      file,
      message: "Local .env is not gitignored — one git add away from committing keys.",
    }));
    return r;
  }

  return result(
    "pass",
    "Tracked .env file",
    "No .env files tracked by git (gitignored local .env files are fine and are never read).",
  );
}

// ===========================================================================
// b3. PACKAGE MANIFEST INTEGRITY
// ===========================================================================
// "Not checkable is not GO." A package.json that EXISTS but does not parse means
// npm can't install, the build can't run, and the deploy will fail — so the gate
// must NO-GO, not merely warn (that was a false GO: `ship` returned GO on a
// corrupt manifest because the build gate could only warn "could not run"). The
// BOM case was patched in 0.6.2; this makes the principle general. A repo with
// NO package.json is a legitimate non-Node project → neutral skip.
export function checkManifest(cwd, project = null) {
  const p = project || detectProject(cwd);
  if (p.packageJsonBroken) {
    return result(
      "fail",
      "Package manifest",
      "package.json exists but is not valid JSON — npm install, the build, and the deploy will all fail until it parses.",
      [
        "Fix the syntax (a trailing comma, a missing quote, smart quotes, or a mid-file BOM are the usual causes), then re-run.",
      ],
    );
  }
  if (!p.packageJsonExists) {
    return result(
      "skip",
      "Package manifest",
      "Skipped — no package.json (not a Node project). Nothing to validate.",
    );
  }
  return result("pass", "Package manifest", "package.json is present and valid JSON.");
}

// ===========================================================================
// c. BUILD + TYPECHECK
// ===========================================================================
// Default: `npx tsc --noEmit` (fast). `--build` also runs `npm run build`.
// BLOCK on either failing; print the tail of the output so the founder sees
// the actual error without scrollback.

/** Default wall-clock budget for typecheck / build (finding: gate-build-no-timeout). */
const DEFAULT_CHECK_TIMEOUT_MS = 10 * 60 * 1000; // 10 minutes

function runCapture(cmd, args, cwd, opts = {}) {
  // Project-controlled compilers/build scripts inherit a credential-scrubbed
  // environment only — never GITHUB_TOKEN, OIDC tokens, getAdvantage API keys,
  // npm/cloud/DB secrets, or generic TOKEN/SECRET/PASSWORD material.
  const childEnv = scrubCredentialEnv(opts.env || process.env);
  try {
    const out = execFileSync(cmd, args, {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      maxBuffer: 32 * 1024 * 1024,
      // On Windows npm is a .cmd shim — shell:true lets it resolve. When we call
      // an absolute path through `node` (the tsc case) we pass shell:false so the
      // path is never re-parsed by cmd.exe.
      shell: opts.shell ?? process.platform === "win32",
      timeout: opts.timeout ?? DEFAULT_CHECK_TIMEOUT_MS,
      killSignal: "SIGTERM",
      env: childEnv,
    });
    return { ok: true, out };
  } catch (e) {
    // Node sets e.killed / signal on timeout; surface a clear message.
    if (e.killed || e.signal === "SIGTERM" || /ETIMEDOUT|timed out/i.test(String(e.message || ""))) {
      const mins = Math.round((opts.timeout ?? DEFAULT_CHECK_TIMEOUT_MS) / 60000);
      return {
        ok: false,
        out: `Command timed out after ${mins} minute${pl(mins)}: ${cmd} ${args.join(" ")}`,
        timedOut: true,
      };
    }
    const out = `${e.stdout || ""}${e.stderr || ""}`.trim();
    return { ok: false, out: out || String(e.message || e) };
  }
}

function tail(text, n = 25) {
  const lines = text.split("\n").filter(Boolean);
  return lines.slice(-n);
}

export function checkTypecheck(cwd, project = null) {
  const p = project || detectProject(cwd);

  // Only run tsc on a repo that is actually typecheckable: a tsconfig.json AND a
  // `typescript` dependency. On a plain-Node repo, blindly running `npx tsc`
  // would download TypeScript and either fail (no config) or flag JS files —
  // a FALSE NO-GO. Degrade to a clearly-labelled skip instead.
  if (!p.typecheckable) {
    // A broken manifest can't confirm the TypeScript setup. The Package manifest
    // check owns the NO-GO for that (a broken manifest is a hard block), so here
    // we skip and point at it rather than emitting a second, weaker signal.
    if (p.packageJsonBroken && p.hasTsConfig) {
      return result(
        "skip",
        "Typecheck",
        "Skipped — package.json could not be parsed, so the TypeScript setup can't be confirmed (the Package manifest check blocks on this). Fix the JSON, then re-run.",
      );
    }
    const why = !p.hasTsConfig && !p.hasTypeScript
      ? "no tsconfig.json and no typescript dependency"
      : !p.hasTsConfig
        ? "no tsconfig.json"
        : "typescript is not a dependency";
    return result(
      "skip",
      "Typecheck",
      `Skipped — this is a ${p.label} (${why}). Nothing to typecheck.`,
    );
  }

  // Resolve the LOCALLY INSTALLED TypeScript compiler and run it via `node`.
  // NEVER `npx --yes tsc`: when typescript is declared but not installed (a
  // fresh clone, or CI with no install step), npx would download and execute a
  // SQUATTED third-party package literally named `tsc` and we'd mislabel its
  // output as type errors. A trust gate must not fetch-and-run unvetted code.
  const tscJs = path.join(cwd, "node_modules", "typescript", "bin", "tsc");
  if (!existsSync(tscJs)) {
    return result(
      "warn",
      "Typecheck",
      "TypeScript is declared but not installed (no node_modules/typescript). Run `npm install`, then re-run — the gate never downloads a compiler.",
    );
  }
  const r = runCapture(process.execPath, [tscJs, "--noEmit"], cwd, { shell: false });
  if (r.ok) {
    return result("pass", "Typecheck (tsc --noEmit)", "TypeScript compiled with no type errors.");
  }
  return result(
    "fail",
    "Typecheck (tsc --noEmit)",
    "tsc reported type errors — fix them before shipping.",
    tail(r.out, 25),
  );
}

// Run the project's OWN `build` script (whatever it is — Next, Vite, tsc -b, a
// plain `node build.js`). We don't assume Next.js. If there is no build script,
// that's not a failure — many libraries/CLIs have nothing to build — so we skip
// honestly rather than invent a NO-GO.
export function checkBuild(cwd, project = null) {
  const p = project || detectProject(cwd);

  if (!p.hasBuildScript) {
    // A broken/BOM'd package.json must NEVER read as "(no package.json)" and
    // silently pass the gate (that was a false GO). The Package manifest check
    // owns the NO-GO for an unparseable manifest; defer to it here so ship
    // reports ONE clear blocking reason, not a weaker "could not run" warning
    // that still lets the verdict be GO.
    if (p.packageJsonBroken) {
      return result(
        "skip",
        "Build",
        "Skipped — package.json could not be parsed, so the build script can't be determined (the Package manifest check blocks on this). Fix the JSON, then re-run.",
      );
    }
    return result(
      "skip",
      "Build",
      `Skipped — ${p.packageJsonExists ? 'no "build" script in package.json' : "no package.json"}. Nothing to build.`,
    );
  }

  const r = runCapture("npm", ["run", "build"], cwd);
  if (r.ok) {
    return result("pass", `Production build (npm run build)`, `\`${p.buildCmd}\` completed successfully.`);
  }
  return result(
    "fail",
    "Production build (npm run build)",
    r.timedOut
      ? "The build timed out (10 min budget) — fix a hang or run the build yourself before shipping."
      : "The build failed — fix it before shipping.",
    tail(r.out, 30),
  );
}

// ===========================================================================
// d. SCHEMA-BUMP CHECK
// ===========================================================================
// db.ts uses a SCHEMA_VERSION sentinel: additive DDL is SKIPPED on an existing
// prod DB whose stored version is already >= SCHEMA_VERSION. So a DDL change
// that forgets to bump SCHEMA_VERSION builds + passes every proof on a fresh
// PGlite DB, then silently no-ops in prod. We diff db.ts (committed vs the
// merge-base with main, PLUS any uncommitted edits): if DDL-ish lines changed
// but the `const SCHEMA_VERSION = N;` line did NOT, WARN loudly.

const DDL_RE = /\b(CREATE\s+TABLE|ADD\s+COLUMN|ALTER\s+TABLE|CREATE\s+(?:UNIQUE\s+)?INDEX|DROP\s+(?:TABLE|COLUMN|INDEX))\b/i;
const VERSION_RE = /SCHEMA_VERSION\s*=\s*\d+/;

export function checkSchemaBump(cwd, baseRef = "main", project = null) {
  const p = project || detectProject(cwd);

  // This check is specific to the SCHEMA_VERSION-sentinel pattern (a db file
  // whose additive DDL is gated behind a version constant). A repo that doesn't
  // use that pattern can't have this bug, so asserting it there would be a
  // false signal. Skip honestly when the pattern isn't present.
  if (!p.hasSchemaVersionPattern) {
    return result(
      "skip",
      "Schema-bump check",
      "Skipped — no SCHEMA_VERSION-sentinel db file in this repo (pattern doesn't apply).",
    );
  }
  const DB_PATH = p.schemaDbPath;

  // Combined diff = (merge-base…HEAD committed) + (working-tree uncommitted).
  // Use `git diff base...HEAD` for the committed delta on this lane, then a
  // plain `git diff HEAD` for anything not yet committed. We never EDIT db.ts —
  // this only READS the diff.
  const haveBase = !!gitSafe(["rev-parse", "--verify", "--quiet", baseRef], { cwd });
  let committedDiff = "";
  if (haveBase) {
    // base...HEAD = changes on HEAD since it diverged from base (symmetric range).
    committedDiff = gitSafe(["diff", `${baseRef}...HEAD`, "--", DB_PATH], { cwd });
  }
  const uncommittedDiff = gitSafe(["diff", "HEAD", "--", DB_PATH], { cwd });
  const combined = `${committedDiff}\n${uncommittedDiff}`;

  // Only consider ADDED/REMOVED lines (diff bodies, prefixed +/-), not context.
  const changedLines = combined
    .split("\n")
    .filter((l) => /^[+-]/.test(l) && !/^[+-]{3}\s/.test(l)); // skip +++/--- headers

  if (changedLines.length === 0) {
    if (!haveBase) {
      return result(
        "pass",
        "Schema-bump check",
        `No changes to ${DB_PATH} in the working tree (base ref '${baseRef}' not found, so the committed lane delta was skipped).`,
      );
    }
    return result("pass", "Schema-bump check", `No changes to ${DB_PATH} vs ${baseRef}.`);
  }

  const ddlChanged = changedLines.some((l) => DDL_RE.test(l));
  const versionChanged = changedLines.some((l) => VERSION_RE.test(l));

  if (ddlChanged && !versionChanged) {
    return result(
      "warn",
      "Schema-bump check",
      `${DB_PATH} has DDL-ish changes but SCHEMA_VERSION was NOT bumped.`,
      [
        "Additive DDL (CREATE TABLE / ADD COLUMN / ALTER / CREATE INDEX) is SKIPPED on an existing prod DB",
        "whose stored version already matches — so it builds + passes proofs on fresh PGlite, then silently",
        "no-ops in prod. Bump `const SCHEMA_VERSION` (and coordinate the migration). See the schema-version memory.",
        ...changedLines.filter((l) => DDL_RE.test(l)).slice(0, 6).map((l) => l.trim()),
      ],
    );
  }

  if (ddlChanged && versionChanged) {
    return result("pass", "Schema-bump check", `${DB_PATH} changed DDL and SCHEMA_VERSION was bumped alongside it.`);
  }

  return result("pass", "Schema-bump check", `${DB_PATH} changed but no DDL-shaped statements were touched.`);
}

// ===========================================================================
// e. SUPABASE RLS / UNGATED MUTATIONS (static policy-state model)
// ===========================================================================
// Local-only static check over Supabase migration SQL (+ optional Edge
// Function sources). Tracks ENABLE/DISABLE RLS and CREATE POLICY per table
// across migration files ordered by path name, then evaluates the FINAL
// static state.
//
// Proven risk (NO-GO / fail):
//   • public schema table with final RLS disabled (or never enabled after
//     CREATE TABLE) — classic AI-app public write surface via PostgREST
//   • CREATE POLICY with USING (true) / WITH CHECK (true) on write commands
//     (INSERT/UPDATE/DELETE/ALL) for public/anon/authenticated (or open TO)
//
// Incomplete / dynamic / malformed → warn or skip, NEVER pass claiming security.
// No Supabase migration/function evidence → honest skip (not a green seal).
// Does NOT execute SQL, call Supabase, or prove end-to-end authorization.
// Comments stripped; single-quoted + dollar-quoted interiors masked (spaces,
// newlines kept) so COMMENT/DEFAULT/$$ bodies cannot fake top-level RLS DDL.
// Test/fixture path patterns ignored.

const SUPABASE_RLS_LABEL = "Supabase RLS / ungated mutations";

/** Paths that look like test/fixture samples — never produce findings. */
function isSupabaseFixturePath(rel) {
  const p = String(rel || "").replace(/\\/g, "/").toLowerCase();
  if (
    /(^|\/)(tests?|__tests__|fixtures?|__fixtures__|mocks?|__mocks__|samples?|testdata|goldens?)(\/|$)/.test(p)
  ) {
    return true;
  }
  if (/\.(test|spec)\.(sql|ts|js|mjs|cjs|tsx|jsx)$/.test(p)) return true;
  if (/(^|\/)(docs?|examples?|demo)(\/|$)/.test(p) && !/supabase\//.test(p)) return true;
  return false;
}

/** True when a tracked path is a Supabase migration SQL file. */
function isSupabaseMigrationSql(rel) {
  const p = String(rel || "").replace(/\\/g, "/");
  if (!/\.sql$/i.test(p)) return false;
  // Canonical layout + common variants under monorepos.
  if (/\/supabase\/migrations\//i.test(`/${p}`)) return true;
  if (/^supabase\/migrations\//i.test(p)) return true;
  return false;
}

/** True when a tracked path is a Supabase Edge Function source file. */
function isSupabaseEdgeFunctionSource(rel) {
  const p = String(rel || "").replace(/\\/g, "/");
  if (!/\.(ts|js|mjs|tsx|jsx)$/i.test(p)) return false;
  if (/\/supabase\/functions\//i.test(`/${p}`)) return true;
  if (/^supabase\/functions\//i.test(p)) return true;
  return false;
}

/**
 * Try to read a PostgreSQL dollar-quote delimiter starting at `i` (`$tag$` or `$$`).
 * Returns the delimiter string or null.
 */
function matchDollarQuoteDelim(s, i) {
  if (s[i] !== "$") return null;
  let j = i + 1;
  while (j < s.length && /[A-Za-z0-9_]/.test(s[j])) j++;
  if (j < s.length && s[j] === "$") return s.slice(i, j + 1);
  return null;
}

/** Strip SQL line/block comments so commented policy text never matches. */
function stripSqlComments(text) {
  let out = "";
  let i = 0;
  const s = String(text || "");
  let inLine = false;
  let inBlock = false;
  let inSingle = false;
  let inDouble = false;
  let dollarDelim = null; // active $tag$ / $$ open delimiter, or null
  while (i < s.length) {
    const ch = s[i];
    const next = s[i + 1];
    if (inLine) {
      if (ch === "\n") {
        inLine = false;
        out += ch;
      }
      i++;
      continue;
    }
    if (inBlock) {
      if (ch === "*" && next === "/") {
        inBlock = false;
        i += 2;
        out += "  ";
        continue;
      }
      // Preserve newlines so line numbers stay stable for residual text.
      if (ch === "\n") out += "\n";
      else out += " ";
      i++;
      continue;
    }
    // Inside dollar-quoted body: copy through (mask pass neutralizes DDL);
    // do not treat -- / /* as comments.
    if (dollarDelim) {
      if (s.startsWith(dollarDelim, i)) {
        out += dollarDelim;
        i += dollarDelim.length;
        dollarDelim = null;
        continue;
      }
      out += ch;
      i++;
      continue;
    }
    if (inSingle) {
      out += ch;
      if (ch === "'" && next === "'") {
        out += next;
        i += 2;
        continue;
      }
      if (ch === "'") inSingle = false;
      i++;
      continue;
    }
    if (inDouble) {
      out += ch;
      if (ch === '"') inDouble = false;
      i++;
      continue;
    }
    if (ch === "-" && next === "-") {
      inLine = true;
      out += "  ";
      i += 2;
      continue;
    }
    if (ch === "/" && next === "*") {
      inBlock = true;
      out += "  ";
      i += 2;
      continue;
    }
    if (ch === "'") {
      inSingle = true;
      out += ch;
      i++;
      continue;
    }
    if (ch === '"') {
      inDouble = true;
      out += ch;
      i++;
      continue;
    }
    const dq = matchDollarQuoteDelim(s, i);
    if (dq) {
      dollarDelim = dq;
      out += dq;
      i += dq.length;
      continue;
    }
    out += ch;
    i++;
  }
  return out;
}

/**
 * Mask interiors of SQL single-quoted string literals and dollar-quoted bodies
 * so DDL-like text inside them cannot match top-level migration regexes.
 * Preserves newlines (and overall layout) so lineOfOffset stays accurate.
 * Handles '' escapes inside '…' and $tag$…$tag$ / $$…$$ dollar quotes.
 */
function maskSqlQuotedLiterals(text) {
  let out = "";
  let i = 0;
  const s = String(text || "");
  while (i < s.length) {
    const ch = s[i];

    // Dollar-quote: $tag$ … $tag$ or $$ … $$
    const open = matchDollarQuoteDelim(s, i);
    if (open) {
      out += open;
      i += open.length;
      while (i < s.length) {
        if (s.startsWith(open, i)) {
          out += open;
          i += open.length;
          break;
        }
        if (s[i] === "\n") out += "\n";
        else out += " ";
        i++;
      }
      continue;
    }

    // Single-quoted string literal (including '' escapes).
    if (ch === "'") {
      out += "'";
      i++;
      while (i < s.length) {
        const c = s[i];
        if (c === "'" && s[i + 1] === "'") {
          // Escaped quote pair — neutralize both chars; keep length stable.
          out += "  ";
          i += 2;
          continue;
        }
        if (c === "'") {
          out += "'";
          i++;
          break;
        }
        if (c === "\n") out += "\n";
        else out += " ";
        i++;
      }
      continue;
    }

    out += ch;
    i++;
  }
  return out;
}

/**
 * Normalize one SQL identifier: unquoted → lowercase; quoted → preserve case
 * (Postgres folds unquoted idents; quoted "Bar" ≠ bar). Handles "" escapes.
 */
function normalizeIdent(raw) {
  const s = String(raw || "").trim();
  if (!s) return null;
  if (s.length >= 2 && s.startsWith('"') && s.endsWith('"')) {
    return s.slice(1, -1).replace(/""/g, '"');
  }
  // Unquoted: strip any residual quotes defensively, fold case.
  return s.replace(/"/g, "").toLowerCase();
}

/**
 * Normalize schema.table (default schema = public).
 * Quoted mixed-case is preserved: public."Bar" ≠ public.bar;
 * public."bar" == public.bar (quoted lowercase merges with unquoted fold).
 */
function normalizeTableName(raw) {
  const t = String(raw || "").trim();
  if (!t) return null;
  // Prefer structured parse so quotes around either part survive.
  const two = /^((?:"[^"]+"|[\w]+))\s*\.\s*((?:"[^"]+"|[\w]+))$/.exec(t);
  if (two) {
    const schema = normalizeIdent(two[1]);
    const name = normalizeIdent(two[2]);
    if (!schema || !name) return null;
    return { schema, name, full: `${schema}.${name}` };
  }
  const one = /^((?:"[^"]+"|[\w]+))$/.exec(t);
  if (one) {
    const name = normalizeIdent(one[1]);
    if (!name) return null;
    return { schema: "public", name, full: `public.${name}` };
  }
  // Fallback: loose split (legacy / partially-stripped forms).
  const parts = t.split(".").map((p) => p.trim()).filter(Boolean);
  if (parts.length === 1) {
    const name = normalizeIdent(parts[0]);
    if (!name) return null;
    return { schema: "public", name, full: `public.${name}` };
  }
  if (parts.length >= 2) {
    const schema = normalizeIdent(parts[0]);
    const name = normalizeIdent(parts[1]);
    if (!schema || !name) return null;
    return { schema, name, full: `${schema}.${name}` };
  }
  return null;
}

/** True when a parenthesized SQL expression is literally `true` (optional casts/whitespace). */
function isLiteralTrueExpr(expr) {
  if (expr == null) return false;
  const e = String(expr)
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/--[^\n]*/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
  // pure true, true::boolean, (true), (((true)))
  let s = e;
  while (s.startsWith("(") && s.endsWith(")")) {
    s = s.slice(1, -1).trim();
  }
  return s === "true" || s === "true::boolean" || s === "true::bool";
}

/**
 * Extract balanced parentheses content starting at `openIdx` (must point at `(`).
 * Returns { inner, end } or null if unbalanced / too deep / dynamic.
 */
function extractParen(text, openIdx) {
  if (openIdx < 0 || text[openIdx] !== "(") return null;
  let depth = 0;
  let inSingle = false;
  for (let i = openIdx; i < text.length; i++) {
    const ch = text[i];
    if (inSingle) {
      if (ch === "'" && text[i + 1] === "'") {
        i++;
        continue;
      }
      if (ch === "'") inSingle = false;
      continue;
    }
    if (ch === "'") {
      inSingle = true;
      continue;
    }
    if (ch === "(") depth++;
    else if (ch === ")") {
      depth--;
      if (depth === 0) return { inner: text.slice(openIdx + 1, i), end: i };
    }
  }
  return null; // unbalanced
}

/** 1-based line of a character offset (text may still contain original newlines). */
function lineOfOffset(text, offset) {
  let line = 1;
  const n = Math.min(offset, text.length);
  for (let i = 0; i < n; i++) if (text[i] === "\n") line++;
  return line;
}

/**
 * Extract `DO [LANGUAGE …] $tag$ … $tag$` bodies (comments already stripped).
 * Bodies are scanned for destroy-path DDL before maskSqlQuotedLiterals blanks them.
 */
function extractDoBlocks(text) {
  const blocks = [];
  const s = String(text || "");
  const doRe = /\bDO\b/gi;
  let m;
  while ((m = doRe.exec(s)) !== null) {
    let i = m.index + 2;
    while (i < s.length && /\s/.test(s[i])) i++;
    // optional LANGUAGE lang_name
    if (s.slice(i, i + 8).toUpperCase() === "LANGUAGE") {
      i += 8;
      while (i < s.length && /\s/.test(s[i])) i++;
      if (s[i] === '"') {
        i++;
        while (i < s.length && s[i] !== '"') i++;
        if (i < s.length && s[i] === '"') i++;
      } else {
        while (i < s.length && /[A-Za-z0-9_]/.test(s[i])) i++;
      }
      while (i < s.length && /\s/.test(s[i])) i++;
    }
    const delim = matchDollarQuoteDelim(s, i);
    if (!delim) continue;
    const bodyStart = i + delim.length;
    let j = bodyStart;
    let found = false;
    while (j < s.length) {
      if (s.startsWith(delim, j)) {
        blocks.push({
          body: s.slice(bodyStart, j),
          bodyStart,
          doIndex: m.index,
        });
        doRe.lastIndex = j + delim.length;
        found = true;
        break;
      }
      j++;
    }
    if (!found) {
      // Unclosed DO body — advance past DO to avoid tight loop.
      doRe.lastIndex = m.index + 2;
    }
  }
  return blocks;
}

/**
 * Pull high-confidence [schema.]table references from a SQL slice (for attaching
 * not_checkable lineage notes). Literals should already be masked when possible.
 */
function extractTableRefsFromSql(slice) {
  /** @type {Map<string, {schema:string,name:string,full:string}>} */
  const found = new Map();
  const re =
    /\b(?:(?:public|auth|storage|extensions|graphql_public)\s*\.\s*)?(?:"[^"]+"|[A-Za-z_][\w$]*)\b/gi;
  // Prefer dotted public.table forms first.
  const dotted =
    /\b((?:"[^"]+"|[\w]+)\s*\.\s*(?:"[^"]+"|[\w]+))/gi;
  for (const m of String(slice || "").matchAll(dotted)) {
    const t = normalizeTableName(m[1]);
    if (!t) continue;
    // Skip schema-only noise like information_schema.columns if any.
    if (t.schema === "pg_catalog" || t.schema === "information_schema") continue;
    found.set(t.full, t);
  }
  // Bare table names after ON / TABLE / POLICY … ON keywords.
  const afterKw =
    /\b(?:ON|TABLE|INTO|FROM|UPDATE|TRUNCATE)\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
  for (const m of String(slice || "").matchAll(afterKw)) {
    const t = normalizeTableName(m[1]);
    if (!t) continue;
    if (t.schema === "pg_catalog" || t.schema === "information_schema") continue;
    found.set(t.full, t);
  }
  void re; // reserved for future wider scans
  return [...found.values()];
}

/** Normalize incomplete notes to a display string. */
function incompleteNoteText(n) {
  if (n == null) return "";
  if (typeof n === "string") return n;
  if (n.message) {
    const loc =
      n.file != null
        ? `${n.file}${n.line != null ? `:${n.line}` : ""}`
        : "";
    return loc ? `${loc}: ${n.message}` : String(n.message);
  }
  return String(n);
}

/**
 * Emit a class-level not_checkable event (+ incomplete note) for lineage confidence.
 * Prefer attaching known table refs; when none, still record an ambient incomplete.
 */
function emitNotCheckable(events, incomplete, o) {
  const snippet = String(o.snippet || o.reason || "unparsed SQL")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 160);
  const reason = o.reason || "unparsed statement";
  const tables = Array.isArray(o.tables) ? o.tables.filter(Boolean) : [];
  const msgBase = o.message || `${reason} — not statically checkable`;
  if (tables.length === 0) {
    // Event path owns the verdict; incomplete is only a diagnostic trail and
    // must not double-emit sql-not-checkable warns after promotion.
    incomplete.push({
      file: o.file,
      line: o.line,
      index: o.index,
      message: msgBase,
      snippet,
      reason,
      viaNotCheckable: true,
    });
    // Ambient: no table attachment — still an event so post-pass can promote
    // against modelled-secure public tables later in the same lineage window.
    events.push({
      kind: "not_checkable",
      table: null,
      file: o.file,
      line: o.line,
      index: o.index,
      reason,
      snippet,
      ambient: true,
    });
    return;
  }
  for (const table of tables) {
    events.push({
      kind: "not_checkable",
      table,
      file: o.file,
      line: o.line,
      index: o.index,
      reason,
      snippet,
    });
    incomplete.push({
      file: o.file,
      line: o.line,
      index: o.index,
      table: table.full,
      message: `${msgBase} (table ${table.full})`,
      snippet,
      reason,
      viaNotCheckable: true,
    });
  }
}

/**
 * After known DO-body event extraction, cover modelled (and deliberately ignored)
 * spans and emit not_checkable for residual statement-like fragments that can
 * still mutate protection. Class fix: unmodelled constructs (e.g. ALTER POLICY)
 * are incomplete, not silent.
 */
function scanDoBodyResidualUnmodeled(rel, text, abs, lineAt, events, incomplete) {
  const n = text.length;
  const covered = new Uint8Array(n);

  const cover = (start, end) => {
    const a = Math.max(0, start);
    const b = Math.min(n, end);
    for (let i = a; i < b; i++) covered[i] = 1;
  };

  const stmtEnd = (start) => {
    let endSemi = text.indexOf(";", start);
    if (endSemi < 0) endSemi = Math.min(n, start + 2048);
    return endSemi + 1;
  };

  // Cover known / deliberately-ignored shapes (same discipline as parsers above).
  const coverRes = [
    /\bDROP\s+TABLE\b/gi,
    /\bDROP\s+POLICY\b/gi,
    /\bDROP\s+SCHEMA\b/gi,
    /\bCREATE\s+POLICY\b/gi,
    /\bALTER\s+SCHEMA\b/gi,
    /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:(?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+(?:DISABLE|ENABLE)\s+ROW\s+LEVEL\s+SECURITY\b/gi,
    /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:(?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+RENAME\s+TO\b/gi,
    /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:(?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+SET\s+SCHEMA\b/gi,
    /\bEXECUTE\s+/gi,
    /\bPERFORM\s+/gi,
  ];
  for (const re of coverRes) {
    for (const m of text.matchAll(re)) {
      cover(m.index, stmtEnd(m.index));
    }
  }

  // Residual security-relevant statement starters still present.
  const residualRe =
    /\b(?:ALTER\s+POLICY|ALTER\s+TABLE|DROP\s+TABLE|DROP\s+POLICY|CREATE\s+POLICY|DROP\s+SCHEMA|ALTER\s+SCHEMA|CREATE\s+TABLE|TRUNCATE|GRANT|REVOKE|EXECUTE)\b/gi;
  for (const m of text.matchAll(residualRe)) {
    if (covered[m.index]) continue;
    const end = stmtEnd(m.index);
    // Skip if majority of the match span is already covered (partial overlap).
    let cov = 0;
    for (let i = m.index; i < end; i++) if (covered[i]) cov++;
    if (cov > (end - m.index) * 0.5) continue;

    const stmt = text.slice(m.index, end);
    const snippet = stmt.replace(/\s+/g, " ").trim().slice(0, 160);
    const tables = extractTableRefsFromSql(stmt);
    const head = snippet.slice(0, 40);
    emitNotCheckable(events, incomplete, {
      file: rel,
      line: lineAt(m.index),
      index: abs(m.index),
      tables,
      reason: `DO-body unmodelled statement (${head}${snippet.length > 40 ? "…" : ""})`,
      message: `DO-body statement not confidently modelled: "${snippet}"`,
      snippet,
    });
    cover(m.index, end);
  }
}

/**
 * Destroy-path / hostile events from inside plpgsql DO bodies.
 * Fail-closed: DROP/DISABLE/DROP POLICY/SET SCHEMA/RENAME/DROP SCHEMA/
 * ALTER SCHEMA RENAME and permissive CREATE POLICY are real events.
 * ENABLE RLS and restrictive CREATE POLICY are never treated as grants from DO bodies.
 * Unmodelled residual DDL (class: ALTER POLICY, dynamic EXECUTE, …) emits
 * not_checkable events so lineage confidence can fail closed.
 */
function parseDoBodyDestroyEvents(rel, strippedText) {
  const events = [];
  const incomplete = [];
  const lineSrc = strippedText;

  for (const block of extractDoBlocks(strippedText)) {
    // Mask nested string / dollar-quote interiors inside the body so
    // PERFORM 'ALTER TABLE … ENABLE RLS' cannot produce phantom events.
    const text = maskSqlQuotedLiterals(block.body);
    const base = block.bodyStart;

    const abs = (localIdx) => base + localIdx;
    const lineAt = (localIdx) => lineOfOffset(lineSrc, abs(localIdx));

    // DROP TABLE [IF EXISTS] [ONLY] name [, ...]
    const dropTableStartRe = /\bDROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?/gi;
    for (const m of text.matchAll(dropTableStartRe)) {
      const start = m.index;
      let endSemi = text.indexOf(";", start);
      if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
      const stmt = text.slice(start, endSemi + 1);
      let listPart = stmt.slice(m[0].length);
      listPart = listPart.replace(/\s*;\s*$/, "");
      listPart = listPart.replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
      listPart = listPart.trim();
      if (!listPart) {
        incomplete.push(
          `${rel}:${lineAt(start)}: DO-body DROP TABLE with empty table list — not fully checkable`,
        );
        continue;
      }
      const afterPrefix = stmt
        .slice(m[0].length)
        .replace(/;\s*$/, "")
        .replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
      const leadWs = (afterPrefix.match(/^\s*/) || [""])[0].length;
      const listAbsBase = start + m[0].length + leadWs;
      const segments = listPart.split(",");
      const tableIdRe = /^((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)$/i;
      let scan = 0;
      let emitted = 0;
      for (const seg of segments) {
        const raw = seg.trim();
        const rawAt = raw ? listPart.indexOf(raw, scan) : scan;
        const segLocal = listAbsBase + (rawAt >= 0 ? rawAt : scan);
        scan = (rawAt >= 0 ? rawAt + raw.length : scan) + 1;
        if (!raw) continue;
        const idM = tableIdRe.exec(raw);
        if (!idM) {
          incomplete.push(
            `${rel}:${lineAt(start)}: DO-body DROP TABLE unparseable element "${raw.slice(0, 60)}"`,
          );
          continue;
        }
        const table = normalizeTableName(idM[1]);
        if (!table) continue;
        events.push({
          kind: "drop_table",
          table,
          file: rel,
          line: lineAt(segLocal),
          index: abs(segLocal),
        });
        emitted++;
      }
      if (emitted === 0) {
        incomplete.push(
          `${rel}:${lineAt(start)}: DO-body DROP TABLE with no parseable table names`,
        );
      }
    }

    // ALTER TABLE … DISABLE ROW LEVEL SECURITY only (never ENABLE as grant)
    const rlsDisRe =
      /\bALTER\s+TABLE\s+(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+DISABLE\s+ROW\s+LEVEL\s+SECURITY\b/gi;
    for (const m of text.matchAll(rlsDisRe)) {
      const table = normalizeTableName(m[1]);
      if (!table) continue;
      events.push({
        kind: "rls",
        table,
        enabled: false,
        file: rel,
        line: lineAt(m.index),
        index: abs(m.index),
        raw: m[0].replace(/\s+/g, " ").trim(),
      });
    }

    // DROP POLICY [IF EXISTS] name ON table
    const dropPolRe =
      /\bDROP\s+POLICY\s+(?:IF\s+EXISTS\s+)?(?:"([^"]+)"|'([^']+)'|([^\s;]+))\s+ON\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
    for (const m of text.matchAll(dropPolRe)) {
      const policyName = m[1] || m[2] || m[3];
      const table = normalizeTableName(m[4]);
      if (!table || !policyName) continue;
      events.push({
        kind: "drop_policy",
        table,
        policyName,
        file: rel,
        line: lineAt(m.index),
        index: abs(m.index),
      });
    }

    // ALTER TABLE … RENAME TO …
    const renameTableRe =
      /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+RENAME\s+TO\s+((?:"[^"]+"|[\w]+))/gi;
    for (const m of text.matchAll(renameTableRe)) {
      const from = normalizeTableName(m[1]);
      if (!from) continue;
      const toTable = normalizeTableName(`${from.schema}.${m[2]}`);
      if (!toTable) continue;
      events.push({
        kind: "rename_table",
        table: from,
        toTable,
        file: rel,
        line: lineAt(m.index),
        index: abs(m.index),
      });
    }

    // ALTER TABLE … SET SCHEMA …
    const setSchemaRe =
      /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+SET\s+SCHEMA\s+((?:"[^"]+"|[\w]+))/gi;
    for (const m of text.matchAll(setSchemaRe)) {
      const from = normalizeTableName(m[1]);
      if (!from) continue;
      const schemaName = normalizeIdent(m[2]);
      if (!schemaName) continue;
      const toTable = { schema: schemaName, name: from.name, full: `${schemaName}.${from.name}` };
      events.push({
        kind: "set_schema",
        table: from,
        toTable,
        file: rel,
        line: lineAt(m.index),
        index: abs(m.index),
      });
    }

    // ALTER SCHEMA old RENAME TO new — bulk relocate (same as top-level ~2069)
    const renameSchemaRe =
      /\bALTER\s+SCHEMA\s+((?:"[^"]+"|[\w]+))\s+RENAME\s+TO\s+((?:"[^"]+"|[\w]+))/gi;
    for (const m of text.matchAll(renameSchemaRe)) {
      const fromSchema = normalizeIdent(m[1]);
      const toSchema = normalizeIdent(m[2]);
      if (!fromSchema || !toSchema) {
        incomplete.push(
          `${rel}:${lineAt(m.index)}: DO-body ALTER SCHEMA RENAME unparseable schema name — not fully checkable`,
        );
        continue;
      }
      if (fromSchema === toSchema) continue;
      events.push({
        kind: "rename_schema",
        fromSchema,
        toSchema,
        file: rel,
        line: lineAt(m.index),
        index: abs(m.index),
      });
    }

    // DROP SCHEMA … CASCADE
    const dropSchemaStartRe = /\bDROP\s+SCHEMA\s+(?:IF\s+EXISTS\s+)?/gi;
    for (const m of text.matchAll(dropSchemaStartRe)) {
      const start = m.index;
      let endSemi = text.indexOf(";", start);
      if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
      const stmt = text.slice(start, endSemi + 1);
      const hasCascade = /\bCASCADE\b/i.test(stmt);
      if (!hasCascade) continue;
      let listPart = stmt.slice(m[0].length);
      listPart = listPart.replace(/\s*;\s*$/, "");
      listPart = listPart.replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
      listPart = listPart.trim();
      if (!listPart) continue;
      const afterPrefix = stmt
        .slice(m[0].length)
        .replace(/;\s*$/, "")
        .replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
      const leadWs = (afterPrefix.match(/^\s*/) || [""])[0].length;
      const listAbsBase = start + m[0].length + leadWs;
      const segments = listPart.split(",");
      const schemaIdRe = /^((?:"[^"]+"|[\w]+))$/i;
      let scan = 0;
      for (const seg of segments) {
        const raw = seg.trim();
        const rawAt = raw ? listPart.indexOf(raw, scan) : scan;
        const segLocal = listAbsBase + (rawAt >= 0 ? rawAt : scan);
        scan = (rawAt >= 0 ? rawAt + raw.length : scan) + 1;
        if (!raw) continue;
        const idM = schemaIdRe.exec(raw);
        if (!idM) continue;
        const schema = normalizeIdent(idM[1]);
        if (!schema) continue;
        events.push({
          kind: "drop_schema",
          schema,
          cascade: true,
          file: rel,
          line: lineAt(segLocal),
          index: abs(segLocal),
        });
      }
    }

    // Hostile CREATE POLICY (USING/WITH CHECK true on write) — real event so
    // final-state cannot silent-GO. Restrictive policies are not granted from DO.
    const policyStartRe =
      /\bCREATE\s+POLICY\s+(?:"([^"]+)"|'([^']+)'|([^\s(]+))\s+ON\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
    for (const m of text.matchAll(policyStartRe)) {
      const policyName = m[1] || m[2] || m[3] || "(unnamed)";
      const table = normalizeTableName(m[4]);
      if (!table) continue;
      const start = m.index;
      let endSemi = text.indexOf(";", start);
      if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
      const stmt = text.slice(start, endSemi + 1);

      let forCmd = "ALL";
      const forM = /\bFOR\s+(ALL|SELECT|INSERT|UPDATE|DELETE)\b/i.exec(stmt);
      if (forM) forCmd = forM[1].toUpperCase();

      let roles = ["public"];
      const toM = /\bTO\s+([^;(]+?)(?=\s+(?:USING|WITH\s+CHECK|AS\s+|FOR\s+)|\s*;)/i.exec(stmt);
      if (toM) {
        roles = toM[1]
          .split(",")
          .map((r) => r.trim().replace(/^["']|["']$/g, "").toLowerCase())
          .filter(Boolean);
        if (roles.length === 0) roles = ["public"];
      }

      let usingTrue = false;
      let withCheckTrue = false;
      const usingIdx = stmt.search(/\bUSING\s*\(/i);
      if (usingIdx >= 0) {
        const open = stmt.indexOf("(", usingIdx);
        const bal = extractParen(stmt, open);
        if (bal) usingTrue = isLiteralTrueExpr(bal.inner);
      }
      const wcIdx = stmt.search(/\bWITH\s+CHECK\s*\(/i);
      if (wcIdx >= 0) {
        const open = stmt.indexOf("(", wcIdx);
        const bal = extractParen(stmt, open);
        if (bal) withCheckTrue = isLiteralTrueExpr(bal.inner);
      }

      const writeOpen =
        (forCmd === "INSERT" && withCheckTrue) ||
        (forCmd === "UPDATE" && (usingTrue || withCheckTrue)) ||
        (forCmd === "DELETE" && usingTrue) ||
        (forCmd === "ALL" && (usingTrue || withCheckTrue));

      if (!writeOpen) continue; // restrictive / non-write — do not grant from DO

      events.push({
        kind: "create_policy",
        table,
        policyName,
        forCmd,
        roles,
        usingExpr: usingTrue ? "true" : null,
        withCheckExpr: withCheckTrue ? "true" : null,
        usingTrue,
        withCheckTrue,
        usingParseOk: true,
        withCheckParseOk: true,
        file: rel,
        line: lineAt(start),
        index: abs(start),
        raw: stmt.replace(/\s+/g, " ").trim().slice(0, 200),
      });
    }

    // EXECUTE '<literal>' / EXECUTE $tag$…$tag$ — fail closed when the literal
    // holds destroy-shaped DDL. format()/concat → not_checkable (class lineage).
    const execRe = /\bEXECUTE\s+/gi;
    for (const m of text.matchAll(execRe)) {
      let i = m.index + m[0].length;
      while (i < text.length && /\s/.test(text[i])) i++;
      const dq = matchDollarQuoteDelim(text, i);
      if (dq) {
        // Body was already maskSqlQuotedLiterals'd → dollar interiors are blank.
        // Use the unmasked block.body slice for EXECUTE dollar/string literals.
        continue;
      }
      if (text[i] === "'") {
        // Single-quoted interiors are blanked by mask — re-read from raw body.
        continue;
      }
      // Dynamic EXECUTE format(...) / variable — cannot prove; class not_checkable.
      if (/^format\s*\(/i.test(text.slice(i))) {
        let endSemi = text.indexOf(";", m.index);
        if (endSemi < 0) endSemi = Math.min(text.length, m.index + 2048);
        // Use unmasked body for table refs inside format string literals.
        const rawSlice = block.body.slice(m.index, endSemi + 1);
        const tables = extractTableRefsFromSql(rawSlice);
        const snippet = rawSlice.replace(/\s+/g, " ").trim().slice(0, 160);
        emitNotCheckable(events, incomplete, {
          file: rel,
          line: lineAt(m.index),
          index: abs(m.index),
          tables,
          reason: "DO-body EXECUTE format(…)",
          message: `DO-body EXECUTE format(…) — not statically checkable`,
          snippet,
        });
      } else if (/^[A-Za-z_]/.test(text.slice(i))) {
        // EXECUTE variable / expression — not statically checkable.
        let endSemi = text.indexOf(";", m.index);
        if (endSemi < 0) endSemi = Math.min(text.length, m.index + 256);
        const snippet = text.slice(m.index, endSemi + 1).replace(/\s+/g, " ").trim().slice(0, 160);
        emitNotCheckable(events, incomplete, {
          file: rel,
          line: lineAt(m.index),
          index: abs(m.index),
          tables: [],
          reason: "DO-body EXECUTE dynamic",
          message: `DO-body EXECUTE dynamic expression — not statically checkable`,
          snippet,
        });
      }
    }

    // Re-scan unmasked DO body for EXECUTE '…' / EXECUTE $tag$…$tag$ destroy DDL.
    {
      const rawBody = block.body;
      const execRawRe = /\bEXECUTE\s+/gi;
      for (const m of rawBody.matchAll(execRawRe)) {
        let i = m.index + m[0].length;
        while (i < rawBody.length && /\s/.test(rawBody[i])) i++;
        let lit = null;
        const dq = matchDollarQuoteDelim(rawBody, i);
        if (dq) {
          const bs = i + dq.length;
          const be = rawBody.indexOf(dq, bs);
          if (be < 0) continue;
          lit = rawBody.slice(bs, be);
        } else if (rawBody[i] === "'") {
          let j = i + 1;
          let out = "";
          while (j < rawBody.length) {
            if (rawBody[j] === "'" && rawBody[j + 1] === "'") {
              out += "'";
              j += 2;
              continue;
            }
            if (rawBody[j] === "'") break;
            out += rawBody[j];
            j++;
          }
          lit = out;
        }
        if (!lit) continue;
        if (/\bformat\s*\(/i.test(lit) || /\|\|/.test(lit)) {
          const tables = extractTableRefsFromSql(lit);
          const snippet = lit.replace(/\s+/g, " ").trim().slice(0, 160);
          emitNotCheckable(events, incomplete, {
            file: rel,
            line: lineAt(m.index),
            index: abs(m.index),
            tables,
            reason: "DO-body EXECUTE dynamic string",
            message: `DO-body EXECUTE dynamic string — not statically checkable`,
            snippet,
          });
          continue;
        }
        // Parse destroy paths inside the EXECUTE literal (fail closed).
        const litMasked = maskSqlQuotedLiterals(lit);
        const dropRe =
          /\bDROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
        for (const dm of litMasked.matchAll(dropRe)) {
          const table = normalizeTableName(dm[1]);
          if (!table) continue;
          events.push({
            kind: "drop_table",
            table,
            file: rel,
            line: lineAt(m.index),
            index: abs(m.index),
          });
        }
        const disRe =
          /\bALTER\s+TABLE\s+(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+DISABLE\s+ROW\s+LEVEL\s+SECURITY\b/gi;
        for (const dm of litMasked.matchAll(disRe)) {
          const table = normalizeTableName(dm[1]);
          if (!table) continue;
          events.push({
            kind: "rls",
            table,
            enabled: false,
            file: rel,
            line: lineAt(m.index),
            index: abs(m.index),
            raw: dm[0].replace(/\s+/g, " ").trim(),
          });
        }
      }
    }

    // Class residual: any unmodelled security-relevant DDL left in the DO body
    // (ALTER POLICY is the canonical example — not a bespoke ALTER-only rule;
    // residual scan catches the whole unmodelled class).
    scanDoBodyResidualUnmodeled(rel, text, abs, lineAt, events, incomplete);
  }

  return { events, incomplete };
}

/**
 * Parse one migration file into ordered events against the policy-state model.
 * Returns { events, incomplete: string[] } — incomplete covers malformed bits.
 */
function parseMigrationEvents(rel, rawText) {
  // Comments first. Extract DO $tag$ bodies for destroy-path events BEFORE
  // maskSqlQuotedLiterals blanks every dollar-quoted interior (that mask is
  // correct for string-literal traps, but erases real static DDL inside plpgsql
  // DO blocks → false GO). Then mask and parse top-level as usual.
  const stripped = stripSqlComments(rawText);
  const doParsed = parseDoBodyDestroyEvents(rel, stripped);
  const text = maskSqlQuotedLiterals(stripped);
  const events = [...doParsed.events];
  const incomplete = [...doParsed.incomplete];

  // CREATE TABLE [IF NOT EXISTS] [schema.]name
  const createTableRe =
    /\bCREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
  for (const m of text.matchAll(createTableRe)) {
    const table = normalizeTableName(m[1]);
    if (!table) continue;
    events.push({
      kind: "create_table",
      table,
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
    });
  }

  // DROP TABLE [IF EXISTS] [ONLY] name [, ...] [CASCADE | RESTRICT]
  // Postgres allows optional ONLY once before the first name, and a comma-
  // separated multi-object list. Mirror CREATE POLICY's TO-roles style: slice
  // to statement end, split commas, emit one event each. Single-table capture
  // alone left tables after the first with stale safe state after DROP+CREATE
  // → false GO. Omitting ONLY from the prefix left "ONLY public.bar" as a list
  // segment that failed tableIdRe → incomplete warn + no drop_table → false GO.
  const dropTableStartRe = /\bDROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?/gi;
  for (const m of text.matchAll(dropTableStartRe)) {
    const start = m.index;
    // Slice forward to next semicolon (or 2 KB) — same discipline as CREATE POLICY.
    let endSemi = text.indexOf(";", start);
    if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
    const stmt = text.slice(start, endSemi + 1);

    // List body after DROP TABLE [IF EXISTS] [ONLY]; ends at CASCADE|RESTRICT or ';'.
    let listPart = stmt.slice(m[0].length);
    listPart = listPart.replace(/\s*;\s*$/, "");
    listPart = listPart.replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
    listPart = listPart.trim();

    if (!listPart) {
      incomplete.push(
        `${rel}:${lineOfOffset(text, start)}: DROP TABLE with empty table list — not fully checkable`,
      );
      continue;
    }

    // Per-table absolute indexes: list body base + offset within comma-split list.
    const afterPrefix = stmt.slice(m[0].length).replace(/;\s*$/, "").replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
    const leadWs = (afterPrefix.match(/^\s*/) || [""])[0].length;
    const listAbsBase = start + m[0].length + leadWs;
    const segments = listPart.split(",");
    // High-confidence [schema.]name only; trailing junk → incomplete (fail safe).
    const tableIdRe = /^((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)$/i;
    let scan = 0;
    let emitted = 0;
    for (const seg of segments) {
      const raw = seg.trim();
      const rawAt = raw ? listPart.indexOf(raw, scan) : scan;
      const segAbs = listAbsBase + (rawAt >= 0 ? rawAt : scan);
      scan = (rawAt >= 0 ? rawAt + raw.length : scan) + 1;
      if (!raw) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP TABLE empty list element — not fully checkable`,
        );
        continue;
      }
      const idM = tableIdRe.exec(raw);
      if (!idM) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP TABLE unparseable table element "${raw.slice(0, 60)}" — not fully checkable`,
        );
        continue;
      }
      const table = normalizeTableName(idM[1]);
      if (!table) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP TABLE unparseable table element — not fully checkable`,
        );
        continue;
      }
      events.push({
        kind: "drop_table",
        table,
        file: rel,
        line: lineOfOffset(text, segAbs),
        // Per-table absolute index so multi-drops order correctly vs siblings.
        index: segAbs,
      });
      emitted++;
    }
    if (emitted === 0) {
      incomplete.push(
        `${rel}:${lineOfOffset(text, start)}: DROP TABLE with no parseable table names — not fully checkable`,
      );
    }
  }

  // ALTER TABLE … ENABLE|DISABLE ROW LEVEL SECURITY
  const rlsRe =
    /\bALTER\s+TABLE\s+(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+(ENABLE|DISABLE)\s+ROW\s+LEVEL\s+SECURITY\b/gi;
  for (const m of text.matchAll(rlsRe)) {
    const table = normalizeTableName(m[1]);
    if (!table) continue;
    events.push({
      kind: "rls",
      table,
      enabled: m[2].toUpperCase() === "ENABLE",
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
      raw: m[0].replace(/\s+/g, " ").trim(),
    });
  }

  // CREATE POLICY "name" ON table [AS …] [FOR cmd] [TO roles] [USING (…)] [WITH CHECK (…)]
  // High-confidence static shapes only. Dynamic SQL / EXECUTE format → incomplete.
  const policyStartRe =
    /\bCREATE\s+POLICY\s+(?:"([^"]+)"|'([^']+)'|([^\s(]+))\s+ON\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
  for (const m of text.matchAll(policyStartRe)) {
    const policyName = m[1] || m[2] || m[3] || "(unnamed)";
    const table = normalizeTableName(m[4]);
    if (!table) {
      incomplete.push(`${rel}:${lineOfOffset(text, m.index)}: CREATE POLICY with unparseable table`);
      continue;
    }
    const start = m.index;
    // Slice forward to next semicolon (or 2 KB) for the rest of the statement.
    let endSemi = text.indexOf(";", start);
    if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
    const stmt = text.slice(start, endSemi + 1);
    // Detect dynamic construction we cannot safely classify.
    if (/\|\||format\s*\(|execute\s+/i.test(stmt) && !/USING|WITH\s+CHECK/i.test(stmt)) {
      incomplete.push(`${rel}:${lineOfOffset(text, start)}: dynamic/malformed CREATE POLICY — not statically checkable`);
      continue;
    }

    let forCmd = "ALL";
    const forM = /\bFOR\s+(ALL|SELECT|INSERT|UPDATE|DELETE)\b/i.exec(stmt);
    if (forM) forCmd = forM[1].toUpperCase();

    let roles = ["public"]; // Postgres default when TO is omitted: PUBLIC
    const toM = /\bTO\s+([^;(]+?)(?=\s+(?:USING|WITH\s+CHECK|AS\s+|FOR\s+)|\s*;)/i.exec(stmt);
    if (toM) {
      roles = toM[1]
        .split(",")
        .map((r) => r.trim().replace(/^["']|["']$/g, "").toLowerCase())
        .filter(Boolean);
      if (roles.length === 0) roles = ["public"];
    }

    let usingExpr = null;
    let withCheckExpr = null;
    let usingTrue = false;
    let withCheckTrue = false;
    let usingParseOk = true;
    let withCheckParseOk = true;

    const usingIdx = stmt.search(/\bUSING\s*\(/i);
    if (usingIdx >= 0) {
      const open = stmt.indexOf("(", usingIdx);
      const bal = extractParen(stmt, open);
      if (!bal) {
        usingParseOk = false;
        incomplete.push(`${rel}:${lineOfOffset(text, start)}: unbalanced USING (…) in CREATE POLICY`);
      } else {
        usingExpr = bal.inner;
        usingTrue = isLiteralTrueExpr(bal.inner);
      }
    }

    const wcIdx = stmt.search(/\bWITH\s+CHECK\s*\(/i);
    if (wcIdx >= 0) {
      const open = stmt.indexOf("(", wcIdx);
      const bal = extractParen(stmt, open);
      if (!bal) {
        withCheckParseOk = false;
        incomplete.push(`${rel}:${lineOfOffset(text, start)}: unbalanced WITH CHECK (…) in CREATE POLICY`);
      } else {
        withCheckExpr = bal.inner;
        withCheckTrue = isLiteralTrueExpr(bal.inner);
      }
    }

    events.push({
      kind: "create_policy",
      table,
      policyName,
      forCmd,
      roles,
      usingExpr,
      withCheckExpr,
      usingTrue,
      withCheckTrue,
      usingParseOk,
      withCheckParseOk,
      file: rel,
      line: lineOfOffset(text, start),
      index: start,
      raw: stmt.replace(/\s+/g, " ").trim().slice(0, 200),
    });
  }

  // DROP POLICY [IF EXISTS] name ON table
  const dropPolRe =
    /\bDROP\s+POLICY\s+(?:IF\s+EXISTS\s+)?(?:"([^"]+)"|'([^']+)'|([^\s;]+))\s+ON\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
  for (const m of text.matchAll(dropPolRe)) {
    const policyName = m[1] || m[2] || m[3];
    const table = normalizeTableName(m[4]);
    if (!table || !policyName) continue;
    events.push({
      kind: "drop_policy",
      table,
      policyName,
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
    });
  }

  // ALTER POLICY name ON table [RENAME TO …] | [TO roles] [USING (…)] [WITH CHECK (…)]
  // Without this, opening a previously-restrictive policy via ALTER is a false-GO.
  const alterPolRe =
    /\bALTER\s+POLICY\s+(?:"([^"]+)"|'([^']+)'|([^\s(]+))\s+ON\s+((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)/gi;
  for (const m of text.matchAll(alterPolRe)) {
    const policyName = m[1] || m[2] || m[3];
    const table = normalizeTableName(m[4]);
    if (!table || !policyName) {
      incomplete.push(`${rel}:${lineOfOffset(text, m.index)}: ALTER POLICY with unparseable name/table`);
      continue;
    }
    const start = m.index;
    let endSemi = text.indexOf(";", start);
    if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
    const stmt = text.slice(start, endSemi + 1);

    const renameM = /\bRENAME\s+TO\s+(?:"([^"]+)"|'([^']+)'|([^\s;]+))/i.exec(stmt);
    if (renameM) {
      const renameTo = renameM[1] || renameM[2] || renameM[3];
      events.push({
        kind: "alter_policy",
        table,
        policyName,
        renameTo,
        file: rel,
        line: lineOfOffset(text, start),
        index: start,
      });
      continue;
    }

    let roles = null;
    const toM = /\bTO\s+([^;(]+?)(?=\s+(?:USING|WITH\s+CHECK)|\s*;)/i.exec(stmt);
    if (toM) {
      roles = toM[1]
        .split(",")
        .map((r) => r.trim().replace(/^["']|["']$/g, "").toLowerCase())
        .filter(Boolean);
      if (roles.length === 0) roles = ["public"];
    }

    let usingExpr = null;
    let withCheckExpr = null;
    let usingTrue = false;
    let withCheckTrue = false;
    let usingParseOk = true;
    let withCheckParseOk = true;
    let usingTouched = false;
    let withCheckTouched = false;

    const usingIdx = stmt.search(/\bUSING\s*\(/i);
    if (usingIdx >= 0) {
      usingTouched = true;
      const open = stmt.indexOf("(", usingIdx);
      const bal = extractParen(stmt, open);
      if (!bal) {
        usingParseOk = false;
        incomplete.push(`${rel}:${lineOfOffset(text, start)}: unbalanced USING (…) in ALTER POLICY`);
      } else {
        usingExpr = bal.inner;
        usingTrue = isLiteralTrueExpr(bal.inner);
      }
    }

    const wcIdx = stmt.search(/\bWITH\s+CHECK\s*\(/i);
    if (wcIdx >= 0) {
      withCheckTouched = true;
      const open = stmt.indexOf("(", wcIdx);
      const bal = extractParen(stmt, open);
      if (!bal) {
        withCheckParseOk = false;
        incomplete.push(`${rel}:${lineOfOffset(text, start)}: unbalanced WITH CHECK (…) in ALTER POLICY`);
      } else {
        withCheckExpr = bal.inner;
        withCheckTrue = isLiteralTrueExpr(bal.inner);
      }
    }

    if (!usingTouched && !withCheckTouched && !roles) {
      incomplete.push(
        `${rel}:${lineOfOffset(text, start)}: ALTER POLICY without parseable USING/WITH CHECK/TO/RENAME — not fully checkable`,
      );
    }

    events.push({
      kind: "alter_policy",
      table,
      policyName,
      roles,
      usingExpr,
      withCheckExpr,
      usingTrue,
      withCheckTrue,
      usingParseOk,
      withCheckParseOk,
      usingTouched,
      withCheckTouched,
      file: rel,
      line: lineOfOffset(text, start),
      index: start,
      raw: stmt.replace(/\s+/g, " ").trim().slice(0, 200),
    });
  }

  // ALTER TABLE [IF EXISTS] [schema.]old RENAME TO new
  // Move modeled RLS/policy state with the rename to avoid false-GO under the new name.
  const renameTableRe =
    /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+RENAME\s+TO\s+((?:"[^"]+"|[\w]+))/gi;
  for (const m of text.matchAll(renameTableRe)) {
    const from = normalizeTableName(m[1]);
    if (!from) continue;
    // RENAME TO only renames the relation within the same schema.
    // Keep quotes on the target so normalizeIdent preserves mixed case.
    const toTable = normalizeTableName(`${from.schema}.${m[2]}`);
    if (!toTable) continue;
    events.push({
      kind: "rename_table",
      table: from,
      toTable,
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
    });
  }

  // ALTER TABLE [IF EXISTS] [ONLY] name SET SCHEMA new_schema
  // Moving a secured public table out of public frees the old name; a naked
  // CREATE of that name must not inherit the stranded safe state → false GO.
  const setSchemaRe =
    /\bALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?((?:"[^"]+"|[\w]+)(?:\s*\.\s*(?:"[^"]+"|[\w]+))?)\s+SET\s+SCHEMA\s+((?:"[^"]+"|[\w]+))/gi;
  for (const m of text.matchAll(setSchemaRe)) {
    const from = normalizeTableName(m[1]);
    if (!from) continue;
    const schemaName = normalizeIdent(m[2]);
    if (!schemaName) continue;
    const toTable = { schema: schemaName, name: from.name, full: `${schemaName}.${from.name}` };
    events.push({
      kind: "set_schema",
      table: from,
      toTable,
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
    });
  }

  // ALTER SCHEMA old RENAME TO new — bulk relocate every modeled table whose
  // schema matches `old` into `new`, freeing the vacated schema name so a later
  // CREATE SCHEMA old + naked CREATE TABLE cannot inherit stranded safe state.
  const renameSchemaRe =
    /\bALTER\s+SCHEMA\s+((?:"[^"]+"|[\w]+))\s+RENAME\s+TO\s+((?:"[^"]+"|[\w]+))/gi;
  for (const m of text.matchAll(renameSchemaRe)) {
    const fromSchema = normalizeIdent(m[1]);
    const toSchema = normalizeIdent(m[2]);
    if (!fromSchema || !toSchema || fromSchema === toSchema) continue;
    events.push({
      kind: "rename_schema",
      fromSchema,
      toSchema,
      file: rel,
      line: lineOfOffset(text, m.index),
      index: m.index,
    });
  }

  // DROP SCHEMA [IF EXISTS] name [, ...] [CASCADE | RESTRICT]
  // CASCADE drops every object in the schema. Without clearing modeled tables
  // for that schema, a later naked CREATE of a previously-secured public name
  // reuses stale safe state → false GO. Without CASCADE, Postgres refuses
  // non-empty drops — leave modeled tables intact (no silent clear).
  const dropSchemaStartRe = /\bDROP\s+SCHEMA\s+(?:IF\s+EXISTS\s+)?/gi;
  for (const m of text.matchAll(dropSchemaStartRe)) {
    const start = m.index;
    let endSemi = text.indexOf(";", start);
    if (endSemi < 0) endSemi = Math.min(text.length, start + 2048);
    const stmt = text.slice(start, endSemi + 1);
    const hasCascade = /\bCASCADE\b/i.test(stmt);

    let listPart = stmt.slice(m[0].length);
    listPart = listPart.replace(/\s*;\s*$/, "");
    listPart = listPart.replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
    listPart = listPart.trim();

    if (!listPart) {
      incomplete.push(
        `${rel}:${lineOfOffset(text, start)}: DROP SCHEMA with empty schema list — not fully checkable`,
      );
      continue;
    }

    const afterPrefix = stmt.slice(m[0].length).replace(/;\s*$/, "").replace(/\s+(CASCADE|RESTRICT)\s*$/i, "");
    const leadWs = (afterPrefix.match(/^\s*/) || [""])[0].length;
    const listAbsBase = start + m[0].length + leadWs;
    const segments = listPart.split(",");
    // Schema identifiers only (no dotted names).
    const schemaIdRe = /^((?:"[^"]+"|[\w]+))$/i;
    let scan = 0;
    let emitted = 0;
    for (const seg of segments) {
      const raw = seg.trim();
      const rawAt = raw ? listPart.indexOf(raw, scan) : scan;
      const segAbs = listAbsBase + (rawAt >= 0 ? rawAt : scan);
      scan = (rawAt >= 0 ? rawAt + raw.length : scan) + 1;
      if (!raw) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP SCHEMA empty list element — not fully checkable`,
        );
        continue;
      }
      const idM = schemaIdRe.exec(raw);
      if (!idM) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP SCHEMA unparseable schema element "${raw.slice(0, 60)}" — not fully checkable`,
        );
        continue;
      }
      const schema = normalizeIdent(idM[1]);
      if (!schema) {
        incomplete.push(
          `${rel}:${lineOfOffset(text, start)}: DROP SCHEMA unparseable schema element — not fully checkable`,
        );
        continue;
      }
      // Only CASCADE is a proven destroy of contained tables. RESTRICT / bare
      // DROP SCHEMA leaves objects in place when the schema is non-empty.
      if (hasCascade) {
        events.push({
          kind: "drop_schema",
          schema,
          cascade: true,
          file: rel,
          line: lineOfOffset(text, segAbs),
          index: segAbs,
        });
        emitted++;
      }
    }
    if (hasCascade && emitted === 0) {
      incomplete.push(
        `${rel}:${lineOfOffset(text, start)}: DROP SCHEMA CASCADE with no parseable schema names — not fully checkable`,
      );
    }
  }

  // Sort events in this file by appearance order.
  events.sort((a, b) => a.index - b.index || a.line - b.line);
  return { events, incomplete };
}

/** Roles that count as a client-facing (non service-role) surface. */
function isClientFacingRole(role) {
  const r = String(role || "").toLowerCase();
  if (r === "service_role" || r === "supabase_admin" || r === "postgres") return false;
  // public, anon, authenticated, or any custom role — treat as client-facing
  // when paired with a literal-true predicate (proven ungated for that role).
  return true;
}

/** Write-shaped commands (the ship-risk surface). SELECT-only USING(true) is not write. */
function isWriteCommand(forCmd) {
  const c = String(forCmd || "ALL").toUpperCase();
  return c === "ALL" || c === "INSERT" || c === "UPDATE" || c === "DELETE";
}

/**
 * True when a policy is a proven permissive write open (USING/WITH CHECK true).
 * Used to decide "modelled-secure" (RLS on + at least one non-open policy).
 */
function isProvenPermissiveWritePolicy(pol) {
  if (!pol || !isWriteCommand(pol.forCmd)) return false;
  const clientRoles = (pol.roles || []).filter(isClientFacingRole);
  if (clientRoles.length === 0) return false;
  const forCmd = String(pol.forCmd || "ALL").toUpperCase();
  return (
    (forCmd === "INSERT" && (pol.withCheckTrue || (pol.usingTrue && pol.withCheckExpr == null))) ||
    (forCmd === "UPDATE" && (pol.usingTrue || pol.withCheckTrue)) ||
    (forCmd === "DELETE" && pol.usingTrue) ||
    (forCmd === "ALL" && (pol.usingTrue || pol.withCheckTrue))
  );
}

/** RLS enabled + at least one policy that is not a proven open write. */
function isModelledSecureState(st) {
  if (!st || st.rlsEnabled !== true) return false;
  if (!st.policies || st.policies.size === 0) return false;
  for (const pol of st.policies.values()) {
    if (!isProvenPermissiveWritePolicy(pol)) return true;
  }
  return false;
}

/**
 * Apply ordered events → final per-table state map.
 * Tracks lineage confidence (everSecureSeq / lineageNotCheckable).
 * @returns {Map<string, object>}
 */
function buildPolicyState(allEvents) {
  /** @type {Map<string, any>} */
  const tables = new Map();
  /** Ambient not_checkable events (no table) for post-pass promotion. */
  const ambientNotCheckable = [];

  function ensure(table) {
    const k = table.full;
    if (!tables.has(k)) {
      tables.set(k, {
        table,
        // Postgres default: RLS off until ENABLE. Unknown until we see CREATE or RLS.
        seenCreate: false,
        rlsEnabled: null, // null = never touched; false/true after ALTER
        rlsLast: null, // {file,line,enabled}
        createLoc: null,
        policies: new Map(), // name → policy
        // Lineage confidence: first monotonic seq at which modelled-secure was observed.
        everSecureSeq: null,
        // Later unmodelled statement against this table after secure observation.
        lineageNotCheckable: null, // {file,line,index,seq,reason,snippet}
      });
    }
    return tables.get(k);
  }

  // Monotonic order across sorted events (file path then index) — do not compare
  // raw char offsets across different migration files.
  let seq = 0;

  function noteSecure(st, atSeq) {
    if (st.everSecureSeq == null && isModelledSecureState(st)) {
      st.everSecureSeq = typeof atSeq === "number" ? atSeq : seq;
    }
  }

  function markLineageNotCheckable(st, ev, atSeq) {
    if (!st) return;
    // Once observed secure, any later unmodelled statement blocks.
    if (st.everSecureSeq == null) return;
    if (typeof atSeq === "number" && atSeq < st.everSecureSeq) return;
    // Keep earliest blocking unmodelled statement.
    if (st.lineageNotCheckable && st.lineageNotCheckable.seq <= atSeq) return;
    st.lineageNotCheckable = {
      file: ev.file,
      line: ev.line,
      index: ev.index,
      seq: atSeq,
      reason: ev.reason || "unparsed statement",
      snippet: ev.snippet || "",
    };
  }

  for (const ev of allEvents) {
    const atSeq = seq++;
    if (ev.kind === "not_checkable") {
      if (!ev.table) {
        ambientNotCheckable.push({ ev, atSeq });
        continue;
      }
      const st = ensure(ev.table);
      markLineageNotCheckable(st, ev, atSeq);
      // Rule 2: public table reachable for mutation with uncertain protection —
      // record for evaluate even if never secure (final-state pass would be wrong).
      if (st.table.schema === "public" && st.everSecureSeq == null) {
        st.uncertainNotCheckable = st.uncertainNotCheckable || {
          file: ev.file,
          line: ev.line,
          index: ev.index,
          reason: ev.reason || "unparsed statement",
          snippet: ev.snippet || "",
        };
      }
      continue;
    }
    if (ev.kind === "create_table") {
      // Only reset policy/RLS state for a *fresh* table (not already in the model).
      // CREATE TABLE IF NOT EXISTS on an already-modeled table must not erase proven
      // policies / ENABLE RLS — matching Postgres IF NOT EXISTS no-op semantics.
      // Real reset path: drop_table deletes the entry, so DROP + CREATE starts clean.
      const isFresh = !tables.has(ev.table.full);
      const st = ensure(ev.table);
      st.seenCreate = true;
      st.createLoc = { file: ev.file, line: ev.line };
      if (isFresh) {
        // Fresh table: RLS off by default in Postgres; no policies yet.
        st.rlsEnabled = false;
        st.policies.clear();
        // Fresh identity — prior secure under this name is gone with drop_table;
        // IF NOT EXISTS on existing keeps everSecureSeq.
        st.everSecureSeq = null;
        st.lineageNotCheckable = null;
        st.uncertainNotCheckable = null;
      }
      noteSecure(st, atSeq);
    } else if (ev.kind === "drop_table") {
      tables.delete(ev.table.full);
    } else if (ev.kind === "rls") {
      const st = ensure(ev.table);
      st.rlsEnabled = ev.enabled;
      st.rlsLast = { file: ev.file, line: ev.line, enabled: ev.enabled, raw: ev.raw };
      noteSecure(st, atSeq);
    } else if (ev.kind === "create_policy") {
      const st = ensure(ev.table);
      st.policies.set(ev.policyName.toLowerCase(), ev);
      noteSecure(st, atSeq);
    } else if (ev.kind === "drop_policy") {
      const st = tables.get(ev.table.full);
      if (st) st.policies.delete(String(ev.policyName).toLowerCase());
    } else if (ev.kind === "alter_policy") {
      // Update existing policy predicates / roles / rename in place so ALTER POLICY
      // cannot silently open writes while the model still holds the old USING expr.
      const st = tables.get(ev.table.full) || ensure(ev.table);
      const key = String(ev.policyName).toLowerCase();
      if (ev.renameTo) {
        const prev = st.policies.get(key);
        if (prev) {
          st.policies.delete(key);
          const renamed = { ...prev, policyName: ev.renameTo, file: ev.file, line: ev.line };
          st.policies.set(String(ev.renameTo).toLowerCase(), renamed);
        }
      } else {
        let pol = st.policies.get(key);
        if (!pol) {
          // ALTER without a prior CREATE we saw — seed a minimal policy so a
          // proven-open USING/WITH CHECK still fails closed.
          pol = {
            kind: "alter_policy",
            policyName: ev.policyName,
            table: ev.table,
            forCmd: "ALL",
            roles: ev.roles || ["public"],
            usingExpr: null,
            withCheckExpr: null,
            usingTrue: false,
            withCheckTrue: false,
            usingParseOk: true,
            withCheckParseOk: true,
            file: ev.file,
            line: ev.line,
          };
          st.policies.set(key, pol);
        }
        if (ev.roles) pol.roles = ev.roles;
        if (ev.usingExpr != null || ev.usingTouched) {
          pol.usingExpr = ev.usingExpr;
          pol.usingTrue = !!ev.usingTrue;
          pol.usingParseOk = ev.usingParseOk !== false;
        }
        if (ev.withCheckExpr != null || ev.withCheckTouched) {
          pol.withCheckExpr = ev.withCheckExpr;
          pol.withCheckTrue = !!ev.withCheckTrue;
          pol.withCheckParseOk = ev.withCheckParseOk !== false;
        }
        pol.file = ev.file;
        pol.line = ev.line;
        // Unbalanced/malformed USING/WITH CHECK → not confidently modelled.
        if (ev.usingParseOk === false || ev.withCheckParseOk === false) {
          markLineageNotCheckable(
            st,
            {
              file: ev.file,
              line: ev.line,
              index: ev.index,
              reason: "ALTER POLICY with unparseable USING/WITH CHECK",
              snippet: ev.raw || "ALTER POLICY …",
            },
            atSeq,
          );
        }
      }
      noteSecure(st, atSeq);
    } else if (ev.kind === "rename_table") {
      // Move modeled state to the new name so open policies cannot be stranded
      // under a dead key (false clean under the new name).
      const fromKey = ev.table.full;
      const toKey = ev.toTable.full;
      if (fromKey === toKey) continue;
      const st = tables.get(fromKey);
      if (st) {
        tables.delete(fromKey);
        st.table = ev.toTable;
        // If target already exists, last rename wins (rare in migrations).
        tables.set(toKey, st);
        noteSecure(st, atSeq);
      }
    } else if (ev.kind === "set_schema") {
      // Move modeled state to the new schema-qualified name; free the old key so
      // a naked CREATE of the vacated public name starts fresh (RLS off).
      const fromKey = ev.table.full;
      const toKey = ev.toTable.full;
      if (fromKey === toKey) continue;
      const st = tables.get(fromKey);
      if (st) {
        tables.delete(fromKey);
        st.table = ev.toTable;
        tables.set(toKey, st);
        noteSecure(st, atSeq);
      }
    } else if (ev.kind === "drop_schema") {
      // CASCADE-modeled DROP SCHEMA removes every table in that schema from the
      // policy-state map — same fail-closed posture as drop_table.
      const schema = String(ev.schema || "");
      if (!schema) continue;
      for (const key of [...tables.keys()]) {
        const st = tables.get(key);
        if (st && st.table && String(st.table.schema) === schema) {
          tables.delete(key);
        }
      }
    } else if (ev.kind === "rename_schema") {
      // Bulk-relocate every modeled table from fromSchema → toSchema (same names).
      // Vacates fromSchema so a later CREATE SCHEMA + naked CREATE cannot reuse
      // stranded secure state under the old schema name.
      const fromSchema = String(ev.fromSchema || "");
      const toSchema = String(ev.toSchema || "");
      if (!fromSchema || !toSchema || fromSchema === toSchema) continue;
      for (const key of [...tables.keys()]) {
        const st = tables.get(key);
        if (!st || !st.table || String(st.table.schema) !== fromSchema) continue;
        tables.delete(key);
        const toTable = {
          schema: toSchema,
          name: st.table.name,
          full: `${toSchema}.${st.table.name}`,
        };
        st.table = toTable;
        tables.set(toTable.full, st);
        noteSecure(st, atSeq);
      }
    }
  }

  // Ambient not_checkable (no table ref): attach to every public table that was
  // already modelled-secure before the ambient statement's seq.
  for (const { ev, atSeq } of ambientNotCheckable) {
    for (const st of tables.values()) {
      if (st.table.schema !== "public") continue;
      markLineageNotCheckable(st, ev, atSeq);
    }
  }

  return tables;
}

/**
 * Evaluate final state → findings (fail) + incomplete notes (warn).
 * Class lineage: after modelled-secure, unmodelled later statements → blocking
 * NOT_CHECKABLE (not warn). Disclosure path is always named on those fails.
 */
function evaluatePolicyState(tables) {
  const fails = [];
  const warns = [];

  const lineageRemediation = (tableFull) => [
    `-- Disclosure / escape hatch (fail-closed lineage confidence):`,
    `-- Rewrite the unmodelled statement as top-level static SQL outside DO $$ … $$ / EXECUTE format(…)`,
    `-- so this check can parse the full protection lineage for ${tableFull}.`,
    `-- Example: move ALTER POLICY / dynamic DDL to a plain migration statement, or re-state final protection:`,
    `ALTER TABLE ${tableFull} ENABLE ROW LEVEL SECURITY;`,
    `-- Then (re)create restrictive policies statically, e.g.:`,
    `CREATE POLICY "${String(tableFull).split(".").pop()}_owner_all"`,
    `  ON ${tableFull}`,
    `  FOR ALL`,
    `  TO authenticated`,
    `  USING (auth.uid() = user_id)`,
    `  WITH CHECK (auth.uid() = user_id);`,
    `-- not checkable ≠ GO for previously secured public tables — do not ship until lineage is static.`,
  ];

  for (const st of tables.values()) {
    // Only public schema is the PostgREST default exposure surface we prove.
    if (st.table.schema !== "public") continue;

    // ---- Class lineage NOT_CHECKABLE (after modelled-secure) -------------
    // Must block before a false "pass" on still-looking-secure final state.
    if (st.lineageNotCheckable) {
      const nc = st.lineageNotCheckable;
      const snip = String(nc.snippet || nc.reason || "unparsed SQL").replace(/\s+/g, " ").trim().slice(0, 160);
      fails.push({
        ruleId: "supabase/lineage-not-checkable",
        label: "Table lineage not fully checkable after secure state",
        file: nc.file,
        startLine: nc.line,
        table: st.table.full,
        message:
          `Table ${st.table.full} was previously modelled as RLS-secured, but a later statement could not be confidently parsed` +
          ` (${nc.reason || "unparsed statement"}): "${snip}". ` +
          `Protection of ${st.table.full} cannot be proven — not checkable ≠ GO.`,
        remediation: lineageRemediation(st.table.full),
      });
      // Still surface proven open holes below when present; lineage fail alone is enough to block.
    }

    // ---- Rule 2: public mutation surface with uncertain protection + gap --
    // If we never observed modelled-secure, final state would "pass" only when
    // RLS is on with no open policies — but an unmodelled gap means we cannot
    // establish protection. When RLS is confidently off, rls-disabled owns it.
    if (
      !st.lineageNotCheckable &&
      st.uncertainNotCheckable &&
      st.rlsEnabled !== false &&
      !isModelledSecureState(st)
    ) {
      const nc = st.uncertainNotCheckable;
      const snip = String(nc.snippet || nc.reason || "unparsed SQL").replace(/\s+/g, " ").trim().slice(0, 160);
      fails.push({
        ruleId: "supabase/lineage-not-checkable",
        label: "Public table protection not fully checkable",
        file: nc.file,
        startLine: nc.line,
        table: st.table.full,
        message:
          `Table ${st.table.full} is a public mutation surface whose protection state cannot be confidently established` +
          ` because of unparsed SQL (${nc.reason || "unparsed statement"}): "${snip}". not checkable ≠ GO.`,
        remediation: lineageRemediation(st.table.full),
      });
    }

    // ---- RLS disabled (or never enabled after create) --------------------
    // Proven when we saw CREATE TABLE (default off) or explicit DISABLE, and
    // final rlsEnabled is false.
    if (st.rlsEnabled === false) {
      const loc = st.rlsLast || st.createLoc;
      if (!loc) continue; // no location evidence — do not invent
      const whyDisable = st.rlsLast && st.rlsLast.enabled === false;
      fails.push({
        ruleId: "supabase/rls-disabled",
        label: "RLS disabled on public table",
        file: loc.file,
        startLine: loc.line,
        table: st.table.full,
        message: whyDisable
          ? `Table ${st.table.full} has RLS DISABLED (final migration state) — PostgREST can expose unauthenticated writes when grants allow.`
          : `Table ${st.table.full} was created without ENABLE ROW LEVEL SECURITY (final state: RLS off) — public API clients can mutate rows when grants allow.`,
        remediation: [
          `-- Smallest safe next edit (in a new migration):`,
          `ALTER TABLE ${st.table.full} ENABLE ROW LEVEL SECURITY;`,
          `-- Then add restrictive policies, e.g. owner-only writes:`,
          `CREATE POLICY "${st.table.name}_owner_all"`,
          `  ON ${st.table.full}`,
          `  FOR ALL`,
          `  TO authenticated`,
          `  USING (auth.uid() = user_id)`,
          `  WITH CHECK (auth.uid() = user_id);`,
          `-- Deny-by-default: no policy for 'anon' unless a deliberate public surface.`,
        ],
      });
      continue; // RLS-off dominates; policy details are secondary
    }

    // ---- Permissive write policies (USING/WITH CHECK true) ---------------
    if (st.rlsEnabled === true || st.rlsEnabled === null) {
      // When rlsEnabled is null we never saw CREATE/ENABLE — only policies.
      // A permissive policy still proves a write hole if RLS is (or will be) on;
      // if RLS is never enabled, CREATE POLICY alone is incomplete (warn).
      for (const pol of st.policies.values()) {
        if (!isWriteCommand(pol.forCmd)) continue;
        const clientRoles = (pol.roles || []).filter(isClientFacingRole);
        if (clientRoles.length === 0) continue; // service_role-only — not public

        const writeOpen =
          (pol.forCmd === "INSERT" && (pol.withCheckTrue || (pol.usingTrue && pol.withCheckExpr == null))) ||
          (pol.forCmd === "UPDATE" && (pol.usingTrue || pol.withCheckTrue)) ||
          (pol.forCmd === "DELETE" && pol.usingTrue) ||
          (pol.forCmd === "ALL" && (pol.usingTrue || pol.withCheckTrue));

        // Incomplete parse of USING/WITH CHECK → never claim GO.
        // After modelled-secure (or RLS on), promote to blocking not-checkable.
        if ((!pol.usingParseOk || !pol.withCheckParseOk) && !writeOpen) {
          const finding = {
            ruleId:
              st.everSecureSeq != null || st.rlsEnabled === true
                ? "supabase/lineage-not-checkable"
                : "supabase/policy-not-checkable",
            label: "Policy not fully parseable",
            file: pol.file,
            startLine: pol.line,
            table: st.table.full,
            message: `CREATE POLICY "${pol.policyName}" on ${st.table.full} has unbalanced/malformed USING or WITH CHECK — static analysis cannot prove safety.`,
          };
          if (st.everSecureSeq != null || st.rlsEnabled === true) {
            finding.message +=
              ` Table ${st.table.full} protection lineage is not checkable ≠ GO.`;
            finding.remediation = [
              `-- Disclosure / escape hatch: fix the policy syntax or rewrite as a complete static CREATE POLICY`,
              `-- with balanced USING / WITH CHECK so lineage can be proven for ${st.table.full}.`,
            ];
            fails.push(finding);
          } else {
            warns.push(finding);
          }
          continue;
        }

        if (!writeOpen) continue;

        // If we only saw CREATE POLICY and never ENABLE RLS, the policy is
        // inert until RLS is on — still a proven intent to open writes, but
        // if RLS is off we already NO-GO above. When rlsEnabled is null
        // (policy-only files, no CREATE/ENABLE), treat as fail if clearly
        // permissive — the policy text is the evidence of public write intent
        // once RLS is turned on, and is itself the ship-risk shape.
        if (st.rlsEnabled === null && !st.seenCreate) {
          // Policy without any table/RLS context: still fail on clear USING(true)
          // write policy — that source evidence is the classic Lovable hole.
        }

        const roleList = clientRoles.join(", ");
        const which =
          pol.usingTrue && pol.withCheckTrue
            ? "USING (true) and WITH CHECK (true)"
            : pol.usingTrue
              ? "USING (true)"
              : "WITH CHECK (true)";
        fails.push({
          ruleId: "supabase/permissive-write-policy",
          label: "Permissive write policy (USING/WITH CHECK true)",
          file: pol.file,
          startLine: pol.line,
          table: st.table.full,
          message: `Policy "${pol.policyName}" on ${st.table.full} FOR ${pol.forCmd} TO ${roleList} uses ${which} — any matching role can write/delete without a row predicate.`,
          remediation: [
            `-- Smallest safe next edit: replace the open predicate with an ownership (or equivalent) check.`,
            `-- Example (drop + recreate; adjust column names to your schema):`,
            `DROP POLICY IF EXISTS "${pol.policyName}" ON ${st.table.full};`,
            `CREATE POLICY "${pol.policyName}"`,
            `  ON ${st.table.full}`,
            `  FOR ${pol.forCmd === "ALL" ? "ALL" : pol.forCmd}`,
            `  TO ${clientRoles.includes("authenticated") || clientRoles.includes("public") ? "authenticated" : clientRoles[0]}`,
            `  USING (auth.uid() = user_id)`,
            `  WITH CHECK (auth.uid() = user_id);`,
            `-- Do not ship USING (true) / WITH CHECK (true) on INSERT/UPDATE/DELETE/ALL for anon/authenticated/public.`,
          ],
        });
      }
    }
  }

  return { fails, warns };
}

/**
 * Edge Function secondary scan — high bar only.
 * Never treat service-role clients as public. Dynamic wrappers → warn.
 * Do not infer auth from import/env alone.
 */
function scanEdgeFunctions(files, readText) {
  const warns = [];
  const incomplete = [];

  for (const rel of files) {
    let text;
    try {
      text = readText(rel);
    } catch {
      continue;
    }
    if (!text) continue;

    // Strip // and /* */ comments roughly so commented mutations don't match.
    const cleaned = text
      .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))
      .replace(/(^|[^:])\/\/[^\n]*/g, "$1");

    const hasServiceRole =
      /service[_-]?role/i.test(cleaned) ||
      /SERVICE_ROLE/i.test(text) ||
      /createClient\s*\(\s*[^,]+,\s*[^,)]*service[_-]?role/i.test(cleaned);

    // Explicit service-role client construction → server-only; do not claim public.
    if (hasServiceRole && !/\.from\s*\(/.test(cleaned)) continue;

    // Dynamic table / method — not statically checkable.
    const dynamicFrom =
      /\.from\s*\(\s*[`'"]?\s*\+|`[^`]*\$\{|\.from\s*\(\s*[a-zA-Z_$][\w$]*\s*\)/.test(cleaned) &&
      !/\.from\s*\(\s*['"][a-zA-Z_][\w$]*['"]\s*\)/.test(cleaned);
    const mutRe =
      /\.from\s*\(\s*['"]([a-zA-Z_][\w$]*)['"]\s*\)\s*(?:\.\s*(?:select|insert|update|delete|upsert)\s*\(|[\s\S]{0,120}?\.\s*(insert|update|delete|upsert)\s*\()/gi;

    let sawExplicitMutation = false;
    let sawDynamicMutation = false;
    const mutMethods = new Set();
    let firstMutLine = null;
    let firstMutTable = null;

    for (const m of cleaned.matchAll(mutRe)) {
      const method = (m[2] || (m[0].match(/\.(insert|update|delete|upsert)\s*\(/i) || [])[1] || "").toLowerCase();
      if (!method || method === "select") continue;
      sawExplicitMutation = true;
      mutMethods.add(method);
      if (firstMutLine == null) {
        firstMutLine = lineOfOffset(cleaned, m.index);
        firstMutTable = m[1];
      }
    }

    // Broader dynamic: supabase.from(variable).delete()
    if (
      /\.from\s*\(\s*[a-zA-Z_$][\w$]*\s*\)\s*[\s\S]{0,80}?\.\s*(insert|update|delete|upsert)\s*\(/i.test(
        cleaned,
      )
    ) {
      sawDynamicMutation = true;
    }

    if (dynamicFrom || sawDynamicMutation) {
      incomplete.push({
        ruleId: "supabase/edge-mutation-not-checkable",
        label: "Edge Function mutation not statically checkable",
        file: rel,
        startLine: firstMutLine || 1,
        message: `Edge Function ${rel} uses a dynamic table/wrapper for mutations — static analysis cannot prove whether the call is public or authorized.`,
      });
      continue;
    }

    if (!sawExplicitMutation) continue;

    // Service-role path with explicit mutations: server-only — do NOT claim public access.
    if (hasServiceRole) {
      // Honest non-finding: service role bypasses RLS by design; not a public surface.
      continue;
    }

    // Explicit string-table write without any auth.getUser / getSession / requireAuth
    // evidence in the same file → warn (not fail — edge functions may rely on
    // gateway JWT verification we cannot see statically).
    const hasAuthEvidence =
      /\.auth\s*\.\s*(getUser|getSession|getClaims)\s*\(/.test(cleaned) ||
      /\brequireAuth\b|\bverifyJWT\b|\bassertUser\b/i.test(cleaned) ||
      /Authorization/i.test(cleaned) && /getUser|jwt|bearer/i.test(cleaned);

    if (!hasAuthEvidence) {
      warns.push({
        ruleId: "supabase/edge-ungated-mutation",
        label: "Edge Function mutation without local auth evidence",
        file: rel,
        startLine: firstMutLine || 1,
        message: `Edge Function mutates table "${firstMutTable || "?"}" via .${[...mutMethods].join("/")}() with no local auth.getUser/getSession evidence — not proven public, but not proven gated either.`,
        remediation: [
          `// Smallest safe next edit: verify the caller before mutating.`,
          `const { data: { user }, error } = await supabase.auth.getUser();`,
          `if (error || !user) return new Response("Unauthorized", { status: 401 });`,
          `// Then scope writes with .eq("user_id", user.id) (or equivalent).`,
          `// Static check cannot see gateway JWT settings — confirm them in the dashboard too.`,
        ],
      });
    }
  }

  return { warns, incomplete };
}

/**
 * Supabase RLS / ungated-mutation static check (policy-state table model).
 * @param {string} cwd
 * @returns {{status,label,detail,extra,findings?}}
 */
export function checkSupabaseRls(cwd) {
  // Tracked + untracked-not-ignored (same ship surface as secret scan).
  const allFiles = [];
  {
    const set = new Set();
    for (const f of gitFilesZ(["ls-files"], { cwd })) set.add(f);
    for (const f of gitFilesZ(["ls-files", "--others", "--exclude-standard"], { cwd })) set.add(f);
    allFiles.push(...set);
  }

  const migrations = allFiles
    .filter((f) => isSupabaseMigrationSql(f) && !isSupabaseFixturePath(f))
    .sort((a, b) => a.replace(/\\/g, "/").localeCompare(b.replace(/\\/g, "/")));

  const edgeFns = allFiles
    .filter((f) => isSupabaseEdgeFunctionSource(f) && !isSupabaseFixturePath(f))
    .sort((a, b) => a.replace(/\\/g, "/").localeCompare(b.replace(/\\/g, "/")));

  if (migrations.length === 0 && edgeFns.length === 0) {
    return result(
      "skip",
      SUPABASE_RLS_LABEL,
      "Skipped — no Supabase migration SQL or Edge Function sources found (nothing to check).",
    );
  }

  const readText = (rel) => {
    const abs = path.join(cwd, rel);
    if (!existsSync(abs)) return null;
    try {
      const st = statSync(abs);
      if (!st.isFile() || st.size > MAX_FILE_BYTES) return null;
      const buf = readFileSync(abs);
      // Reuse secret-scan binary skip: null-byte early → skip.
      if (looksBinary(buf)) return null;
      return buf.toString("utf8");
    } catch {
      return null;
    }
  };

  const allEvents = [];
  const incompleteNotes = [];
  let migrationsRead = 0;

  for (const rel of migrations) {
    const raw = readText(rel);
    if (raw == null) {
      incompleteNotes.push(`${rel}: unreadable or oversized — not fully checkable`);
      continue;
    }
    migrationsRead++;
    const { events, incomplete } = parseMigrationEvents(rel, raw);
    allEvents.push(...events);
    incompleteNotes.push(...incomplete);
  }

  // Cross-file order: migration path name (Supabase timestamp prefixes sort correctly).
  allEvents.sort((a, b) => {
    const fa = a.file.replace(/\\/g, "/");
    const fb = b.file.replace(/\\/g, "/");
    if (fa !== fb) return fa.localeCompare(fb);
    return a.index - b.index || a.line - b.line;
  });

  const tables = buildPolicyState(allEvents);
  const { fails, warns: polWarns } = evaluatePolicyState(tables);

  // Edge functions: optional secondary, high bar.
  const edge = edgeFns.length > 0 ? scanEdgeFunctions(edgeFns, readText) : { warns: [], incomplete: [] };

  const allFails = [...fails];
  const allWarns = [...polWarns, ...edge.warns, ...edge.incomplete];
  // Incomplete notes: most stay warns. Notes already promoted via not_checkable
  // events appear as lineage-not-checkable fails above. Remaining notes that
  // name a table which still looks modelled-secure (final pass candidate) are
  // promoted here as a safety net (class fail-closed).
  const secureFinal = new Set();
  for (const st of tables.values()) {
    if (st.table.schema === "public" && isModelledSecureState(st) && !st.lineageNotCheckable) {
      secureFinal.add(st.table.full);
    }
  }
  for (const n of incompleteNotes) {
    // Notes emitted alongside not_checkable events are owned by evaluatePolicyState
    // (lineage-not-checkable fails). Skip so we do not double-emit warn/fail.
    if (typeof n === "object" && n && n.viaNotCheckable) continue;
    const text = incompleteNoteText(n);
    const file =
      typeof n === "object" && n && n.file
        ? n.file
        : String(text).split(":")[0] || "";
    const tableFull =
      typeof n === "object" && n && n.table
        ? n.table
        : null;
    const startLine =
      typeof n === "object" && n && typeof n.line === "number" ? n.line : undefined;
    const snip =
      typeof n === "object" && n && n.snippet
        ? String(n.snippet).replace(/\s+/g, " ").trim().slice(0, 160)
        : "";
    // Already blocking via not_checkable → lineage-not-checkable in evaluatePolicyState;
    // do not also emit a redundant sql-not-checkable warn for the same gap.
    if (tableFull) {
      const st = tables.get(tableFull);
      if (st && st.lineageNotCheckable) continue;
    }
    // Promote when the note attaches to a still-secure-looking public table.
    if (tableFull && secureFinal.has(tableFull)) {
      allFails.push({
        ruleId: "supabase/lineage-not-checkable",
        label: "Table lineage not fully checkable after secure state",
        file,
        startLine,
        table: tableFull,
        message:
          `Table ${tableFull} was modelled as RLS-secured, but migration SQL was not fully checkable` +
          `${snip ? `: "${snip}"` : `: ${text}`}. Protection cannot be proven — not checkable ≠ GO.`,
        remediation: [
          `-- Disclosure / escape hatch: rewrite dynamic/DO-wrapped DDL as top-level static SQL`,
          `-- so lineage for ${tableFull} is fully parseable, then re-run getadvantage check.`,
        ],
      });
      continue;
    }
    allWarns.push({
      ruleId: "supabase/sql-not-checkable",
      label: "SQL not fully checkable",
      file,
      ...(startLine != null ? { startLine } : {}),
      ...(tableFull ? { table: tableFull } : {}),
      message: text,
    });
  }

  const honesty =
    "Static migration/policy evidence only — not a proof of end-to-end authorization or live Supabase config.";

  // Build structured findings for SARIF/JSON.
  const toFinding = (f, level) => ({
    ruleId: f.ruleId,
    label: f.label || f.ruleId,
    file: f.file || undefined,
    ...(typeof f.startLine === "number" ? { startLine: f.startLine } : {}),
    message: f.message,
    ...(f.table ? { table: f.table } : {}),
    level,
  });

  if (allFails.length > 0) {
    const findings = allFails.map((f) => toFinding(f, "fail"));
    // Also attach warns as findings so JSON consumers see incomplete bits.
    for (const w of allWarns) findings.push(toFinding(w, "warn"));

    const extra = [];
    for (const f of allFails.slice(0, 10)) {
      extra.push(`${f.file}${f.startLine ? `:${f.startLine}` : ""} — ${f.message}`);
      if (Array.isArray(f.remediation)) {
        for (const line of f.remediation) extra.push(line);
      }
      extra.push(""); // blank separator
    }
    if (allFails.length > 10) extra.push(`…and ${allFails.length - 10} more proven RLS risks`);
    if (allWarns.length > 0) {
      extra.push(`${allWarns.length} additional incomplete/dynamic note${pl(allWarns.length)} (not GO-cleared):`);
      for (const w of allWarns.slice(0, 5)) {
        extra.push(`  ⚠ ${w.file || ""}${w.startLine ? `:${w.startLine}` : ""} — ${w.message}`);
      }
    }
    extra.push(honesty);

    const r = result(
      "fail",
      SUPABASE_RLS_LABEL,
      `${allFails.length} proven public-write RLS risk${pl(allFails.length)} in migration final state — do not ship until fixed.`,
      extra.filter((line, i, arr) => !(line === "" && arr[i - 1] === "")),
    );
    r.findings = findings;
    return r;
  }

  if (allWarns.length > 0) {
    const findings = allWarns.map((w) => toFinding(w, "warn"));
    const extra = allWarns.slice(0, 15).map(
      (w) => `${w.file || ""}${w.startLine ? `:${w.startLine}` : ""} — ${w.message}`,
    );
    for (const w of allWarns.slice(0, 5)) {
      if (Array.isArray(w.remediation)) for (const line of w.remediation) extra.push(line);
    }
    extra.push(honesty);
    const r = result(
      "warn",
      SUPABASE_RLS_LABEL,
      `${allWarns.length} incomplete/dynamic Supabase surface${pl(allWarns.length)} — not proven safe (not checkable ≠ GO).`,
      extra,
    );
    r.findings = findings;
    return r;
  }

  // Evidence present, final state has no proven open write surface.
  // Pass means "no proven static risk found" — not "authorization verified".
  const tableCount = [...tables.values()].filter((t) => t.table.schema === "public").length;
  return result(
    "pass",
    SUPABASE_RLS_LABEL,
    migrationsRead > 0
      ? `Scanned ${migrationsRead} migration${pl(migrationsRead)} (${tableCount} public table${pl(tableCount)} in final state)${edgeFns.length ? ` + ${edgeFns.length} edge function${pl(edgeFns.length)}` : ""} — no proven permissive public-write RLS surface.`
      : `Scanned ${edgeFns.length} edge function${pl(edgeFns.length)} (no migration SQL) — no proven public-write surface.`,
    [honesty],
  );
}
